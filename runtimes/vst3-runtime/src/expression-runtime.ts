/**
 * The adapter's copy of the expression helpers (`cppRuntime()`), which its
 * interpreter calls: `native/src/generated/ExpressionRuntime.h`, checked in
 * (the adapter is compiled once, without Node) and checked current by a test.
 */

import {
  CPP_INCLUDES,
  CPP_PRAGMAS,
  cppRuntime,
} from '@soundor/runtime-sdk/expression/cpp';

export function renderExpressionRuntime(): string {
  return `// This file was generated by Soundor (scripts/expression-runtime.mjs). Do not edit.
// The helpers of @soundor/expression's C++ compiler, which the interpreter
// (Expression.cpp) calls, so that it computes what compiled expressions do.
#pragma once

${CPP_PRAGMAS}
${CPP_INCLUDES.map((header) => `#include ${header}`).join('\n')}

namespace soundor::vst3::expression
{
${cppRuntime()
  .split('\n')
  .map((line) => (line === '' ? '' : `    ${line}`))
  .join('\n')}
} // namespace soundor::vst3::expression
`;
}
