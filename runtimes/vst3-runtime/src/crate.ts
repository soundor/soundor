/**
 * The Rust crate `soundor build vst3` generates for a project, in its cache
 * (`.soundor/cache/vst3/<profile>/crate`), which Cargo compiles into the one
 * static library the plugin links:
 *
 * - the project's own `lib/` crate, unchanged, as a dependency: its
 *   processor, controller and MIDI (`soundor::export!`'s ABI);
 * - this runtime's `soundor-vst3` crate (rust/), with
 *   `soundor_vst3::plugin!` defining the VST3 runtime's private ABI from the
 *   descriptor, the controller descriptor and the UI's files, embedded with
 *   include_bytes!.
 *
 * Nothing of it is the project's to edit: it is made again by every build.
 */

import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

import { EnvError, RuntimeError, type Logger } from '@soundor/runtime-sdk';

/** This package's Rust crate. */
export function runtimeCrateDir(packageRoot: string): string {
  return join(packageRoot, 'rust');
}

/** The `[package] name` of a Cargo manifest. */
export function cratePackageName(manifest: string): string | undefined {
  let section = '';
  for (const raw of manifest.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    const header = /^\[([^\]]+)\]$/.exec(line);
    if (header) {
      section = header[1]!.trim();
      continue;
    }
    const name = /^name\s*=\s*"([^"]+)"$/.exec(line);
    if (section === 'package' && name) return name[1];
  }
  return undefined;
}

/** A Rust raw string literal of `text`. */
function rustString(text: string): string {
  let hashes = '#';
  while (text.includes(`"${hashes}`)) hashes += '#';
  return `r${hashes}"${text}"${hashes}`;
}

export interface CrateSources {
  /** The project's `lib/Cargo.toml`. */
  readonly libManifest: string;
  /** This package's root. */
  readonly packageRoot: string;
  readonly descriptor: string;
  readonly controllerDescriptor: Uint8Array;
  /** The UI's files to embed, by path. */
  readonly files: readonly { path: string; file: string }[];
  /** A development build's UI directory and log ('' for none). */
  readonly uiDirectory: string;
  readonly logFile: string;
}

/** The generated crate's files: Cargo.toml, src/lib.rs and its data. */
export function renderCrate(sources: CrateSources, packageName: string) {
  const libDir = dirname(resolve(sources.libManifest));
  const cargo = `# Generated by Soundor's VST3 runtime for every build. Do not edit.
[package]
name = "soundor-vst3-plugin"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
path = "src/lib.rs"
crate-type = ["staticlib"]

[dependencies]
plugin = { package = ${JSON.stringify(packageName)}, path = ${JSON.stringify(libDir)} }
soundor-vst3 = { path = ${JSON.stringify(runtimeCrateDir(sources.packageRoot))} }

# Optimized enough to process audio in real time, with debug assertions.
[profile.dev]
opt-level = 1

[profile.release]
debug = false

[workspace]
`;
  // Aligned: the engine reads bytecode in place, which Hermes requires aligned.
  const data = sources.files
    .map(
      (entry, index) =>
        `static FILE_${index}: &soundor_vst3::Aligned<[u8]> = &soundor_vst3::Aligned(*include_bytes!(${rustString(entry.file)}));`,
    )
    .join('\n');
  const files = sources.files
    .map(
      (entry, index) =>
        `    soundor_vst3::File::new(${rustString(entry.path)}, &FILE_${index}.0),`,
    )
    .join('\n');
  const lib = `// Generated by Soundor's VST3 runtime for every build. Do not edit.
//! The plugin's static library: the project's crate (its processor and
//! controller, through \`soundor::export!\`), and what the VST3 adapter asks
//! of it to be this plugin.
#![allow(clippy::all)]

// Linked for its exports (soundor_processor_*, soundor_controller_*, soundor_midi_*).
extern crate plugin as _;

${data}
static FILES: [soundor_vst3::File; ${sources.files.length}] = [
${files}
];

soundor_vst3::plugin!(soundor_vst3::Plugin {
    descriptor: include_bytes!("../descriptor.json"),
    controller_descriptor: include_bytes!("../controller.bin"),
    files: &FILES,
    ui_directory: ${rustString(sources.uiDirectory)},
    log_file: ${rustString(sources.logFile)},
});
`;
  return { cargo, lib };
}

/** Writes the crate into `dir` (only what changed, so Cargo rebuilds only that). */
export async function writeCrate(
  dir: string,
  sources: CrateSources,
): Promise<void> {
  const manifest = await readFile(sources.libManifest, 'utf8');
  const name = cratePackageName(manifest);
  if (name === undefined)
    throw new EnvError(
      `${sources.libManifest} has no [package] name: the plugin's crate cannot be linked.`,
    );
  const { cargo, lib } = renderCrate(sources, name);
  await mkdir(join(dir, 'src'), { recursive: true });
  const write = async (file: string, contents: string | Uint8Array) => {
    const target = join(dir, file);
    if (existsSync(target)) {
      const current = await readFile(target);
      if (Buffer.compare(current, Buffer.from(contents)) === 0) return;
    }
    await writeFile(target, contents);
  };
  await write('Cargo.toml', cargo);
  await write('src/lib.rs', lib);
  await write('descriptor.json', sources.descriptor);
  await write('controller.bin', sources.controllerDescriptor);
}

/**
 * Cargo's arguments for the crate. On Windows, the static C runtime, as the
 * adapter and the engine archives it links with.
 */
export function crateBuildArguments(
  manifest: string,
  options: {
    readonly targetDir: string;
    readonly profile: 'debug' | 'release';
    readonly target: string;
  },
): string[] {
  const staticCrt = options.target.endsWith('-windows-msvc');
  return [
    'build',
    '--manifest-path',
    manifest,
    '--lib',
    '--target',
    options.target,
    '--target-dir',
    options.targetDir,
    '--message-format=json-render-diagnostics',
    ...(options.profile === 'release' ? ['--release'] : []),
    ...(staticCrt
      ? [
          '--config',
          `target.${options.target}.rustflags=["-C", "target-feature=+crt-static"]`,
        ]
      : []),
  ];
}

/** Compiles the crate in `dir`: the static library's path. */
export async function buildCrate(options: {
  readonly dir: string;
  readonly projectRoot: string;
  readonly targetDir: string;
  readonly profile: 'debug' | 'release';
  /** The Rust target triple (targets.ts's rustTarget()). */
  readonly target: string;
  readonly logger: Logger;
  readonly signal?: AbortSignal;
}): Promise<string> {
  const manifest = join(options.dir, 'Cargo.toml');
  const args = crateBuildArguments(manifest, options);

  const libraries: string[] = [];
  const code = await new Promise<number | null>((resolvePromise, reject) => {
    // From the project: its rust-toolchain.toml chooses the toolchain.
    const child = spawn('cargo', args, {
      cwd: options.projectRoot,
      signal: options.signal,
    });
    let pending = '';
    child.stdout.on('data', (chunk: Buffer) => {
      pending += chunk.toString('utf8');
      const lines = pending.split('\n');
      pending = lines.pop() ?? '';
      for (const line of lines) collect(line);
    });
    child.stderr.on('data', (chunk: Buffer) => {
      const text = chunk.toString('utf8').trimEnd();
      if (text.length > 0) options.logger.pipe(text, 'stderr');
    });
    child.on('error', (error: NodeJS.ErrnoException) =>
      reject(
        error.code === 'ENOENT'
          ? new EnvError(
              'Cargo was not found. Install Rust (https://rustup.rs), then run `soundor doctor`.',
            )
          : error,
      ),
    );
    child.on('close', (status) => {
      if (pending.length > 0) collect(pending);
      resolvePromise(status);
    });
  });
  function collect(line: string): void {
    if (!line.startsWith('{')) return;
    try {
      const message = JSON.parse(line) as {
        reason?: string;
        manifest_path?: string;
        target?: { kind?: string[] };
        filenames?: string[];
      };
      if (
        message.reason === 'compiler-artifact' &&
        message.manifest_path !== undefined &&
        resolve(message.manifest_path) === resolve(manifest) &&
        message.target?.kind?.includes('staticlib')
      )
        libraries.push(...(message.filenames ?? []));
    } catch {
      // Not Cargo's JSON.
    }
  }
  if (code !== 0)
    throw new RuntimeError(
      "The plugin's Rust library failed to compile; Cargo's errors are above.",
    );
  const library = libraries.find((file) => /\.(a|lib)$/.test(file));
  if (library === undefined)
    throw new RuntimeError(
      'Cargo built the plugin crate without a static library.',
    );
  return library;
}
