/**
 * The parameters' behavior for the Web host: their mapping, step and text,
 * compiled to JavaScript from the expressions config resolved them into — the
 * same expressions the JUCE runtime compiles to C++. One ES module of plain
 * functions, with the small runtime they call inlined: it imports nothing, so
 * the page bundles it as it is and no compiler reaches the browser.
 */

import { semanticsInputs, type ResolvedParameter } from '@soundor/runtime-sdk';
import { compileJs, JS_RUNTIME } from '@soundor/runtime-sdk/expression/js';

/** `parameters.js`: `behaviors`, in the manifest's order. */
export function renderParameterBehaviors(
  parameters: readonly ResolvedParameter[],
): string {
  const entries = parameters.map((parameter) => {
    const { semantics } = parameter;
    const inputs = semanticsInputs(semantics.valueType);
    const fn = (input: string, expression: unknown, i: object) =>
      `(${input}) => ${compileJs(expression, i as never)}`;
    return `  // ${JSON.stringify(parameter.id)}
  {
    toValue: ${fn('normalized', semantics.toValue, inputs.toValue)},
    toNormalized: ${fn('value', semantics.toNormalized, inputs.toNormalized)},
    constrain: ${fn('value', semantics.constrain, inputs.constrain)},
    format: ${fn('value', semantics.format, inputs.format)},
    parse: ${fn('text', semantics.parse, inputs.parse)},
  },`;
  });
  return `// This file was generated by Soundor. Do not edit.
// The parameters' behavior, compiled from soundor.config; values are plain
// numbers (a boolean's 0 or 1, a choice's option index).

${JS_RUNTIME}
export const behaviors = [
${entries.join('\n')}
];
`;
}
