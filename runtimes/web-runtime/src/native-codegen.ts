/**
 * The TypeScript contract of `soundor:native` for the Web: what
 * `runtimes/web/src/native.ts` implements. The JUCE runtime generates a C++
 * interface from the same model; here the plugin's calls reach the user's
 * TypeScript directly, with no serialization in between.
 *
 * Types match the plugin-facing declaration (`.soundor/generated/native.d.ts`):
 * arguments as the plugin passes them (readonly arrays), results as it
 * receives them. The runtime checks both against the declared types.
 */

import {
  nativeTsChannelType,
  nativeTsType,
  type NativeApiModel,
} from '@soundor/runtime-sdk';

type NativeTypeModel = NativeApiModel['types'][number];

const HEADER = '// This file was generated by Soundor. Do not edit.\n\n';

/** The generated `native.ts`, from a resolved native API model. */
export function renderWebNative(model: NativeApiModel): string {
  const types = model.types.map(renderType);
  const methods = model.methods.map((method) => {
    const args = method.args
      .map((arg) => `${arg.name}: ${nativeTsType(arg.type, 'argument')}`)
      .join(', ');
    const result = nativeTsType(method.returns, 'result');
    return `  ${method.name}(${args}): ${method.async ? `Promise<${result}>` : result};`;
  });
  const api =
    methods.length === 0
      ? 'export type WebNativeApi = Record<never, never>;\n'
      : `export interface WebNativeApi {\n${methods.join('\n')}\n}\n`;
  const publishers = [
    ...(model.channels.length > 0 ? ['nativeChannelPublishers'] : []),
    ...(model.events.length > 0 ? ['nativeEventPublishers'] : []),
  ];
  // As oxfmt formats them: the project may format its generated files.
  const imports =
    publishers.length === 0
      ? ''
      : publishers.length === 1
        ? `import { ${publishers[0]} } from '@soundor/web-runtime/client';\n\n`
        : `import {\n${publishers.map((name) => `  ${name},\n`).join('')}} from '@soundor/web-runtime/client';\n\n`;
  return `${HEADER}${imports}${types.map((type) => `${type}\n\n`).join('')}/**
 * The plugin's native API (soundor:native), as runtimes/web/src/native.ts
 * implements it for the Web. A method added to soundor.config is missing
 * here until it is implemented.
 */
${api}${model.events.length > 0 ? `\n${renderEvents(model.events)}` : ''}${model.channels.length > 0 ? `\n${renderChannels(model.channels)}` : ''}`;
}

/**
 * The publishers of the declared channels, for the project's runtimes/web
 * code: the Web counterpart of the C++ \`native::Channels\`.
 */
function renderChannels(channels: NativeApiModel['channels']): string {
  const members = channels.map((channel) => {
    const type = nativeTsChannelType(channel);
    return channel.kind === 'buffer'
      ? `  /** At most ${channel.maxLength} elements; false, publishing nothing, for more. */
  readonly ${channel.name}: { publish(value: ${type}): boolean };`
      : `  readonly ${channel.name}: { publish(value: ${type}): void };`;
  });
  return `/**
 * The plugin's native channels (soundor:native \`channels\`): publish their
 * latest values from the project's runtimes/web code (an AnalyserNode read
 * every frame, a meter), and the plugin UI receives the newest once a frame.
 * A value replaces one not yet delivered; a buffer is copied.
 */
export interface WebNativeChannels {
${members.join('\n')}
}

export const channels =
  nativeChannelPublishers() as unknown as WebNativeChannels;
`;
}

/**
 * The publishers of the declared events, for runtimes/web/src/native.ts:
 * the Web counterpart of the C++ \`native::Events\`.
 */
function renderEvents(events: NativeApiModel['events']): string {
  const publishers = events.map((event) => {
    const fields = event.fields
      .map((field) => `${field.name}: ${nativeTsType(field.type, 'argument')}`)
      .join('; ');
    const parameter =
      event.fields.length === 0
        ? 'event?: Record<string, never>'
        : `event: { ${fields} }`;
    return `  ${event.name}(${parameter}): boolean;`;
  });
  return `/**
 * The plugin's native events (soundor:native \`events\`): publish one from
 * runtimes/web/src/native.ts, and the plugin UI's
 * subscribers receive it after the call returns, in the order published.
 * Each checks its value and returns whether the page took it (it holds 1024
 * undelivered events and drops newer ones).
 */
export interface WebNativeEvents {
${publishers.join('\n')}
}

export const events = nativeEventPublishers() as unknown as WebNativeEvents;
`;
}

function renderType(type: NativeTypeModel): string {
  switch (type.kind) {
    case 'enum':
      return `export type ${type.name} = ${type.values.map(quote).join(' | ')};`;
    case 'struct': {
      const fields = type.fields.map(
        (field) => `  ${field.name}: ${nativeTsType(field.type, 'result')};`,
      );
      return [`export interface ${type.name} {`, ...fields, '}'].join('\n');
    }
  }
}

/** A string literal in single quotes, as the project writes them. */
function quote(value: string): string {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}
