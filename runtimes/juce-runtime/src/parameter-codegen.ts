/**
 * The parameters' C++: their metadata (`parameters::Info`) and their behavior
 * (`backend::ParameterBehavior`), compiled from the expressions config
 * resolved them into — the expressions the Web runtime compiles to
 * JavaScript. Plain C++ over plain values: the plugin's processor, the host's
 * text requests and the UI all run the same functions, with or without an
 * editor open.
 */

import type { ResolvedParameter } from '@soundor/runtime-sdk';
import { semanticsInputs } from '@soundor/runtime-sdk';
import {
  CPP_INCLUDES,
  CPP_PRAGMAS,
  compileCpp,
  cppRuntime,
  cppStringLiteral,
  cppType,
} from '@soundor/runtime-sdk/expression/cpp';

const HEADER = '// This file was generated by Soundor. Do not edit.\n';

const TYPE: Record<ResolvedParameter['type'], string> = {
  int8: 'Int8',
  uint8: 'Uint8',
  int16: 'Int16',
  uint16: 'Uint16',
  int32: 'Int32',
  uint32: 'Uint32',
  float32: 'Float32',
  boolean: 'Boolean',
  choice: 'Choice',
};

const ACCESS: Record<ResolvedParameter['access'], string> = {
  automatable: 'Automatable',
  manual: 'Manual',
  readOnly: 'ReadOnly',
};

/** A C++ `std::string` initializer of `value` (UTF-8). */
function cppString(value: string): string {
  return cppStringLiteral(value);
}

function cppDouble(value: number): string {
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
}

/** The plain range, default and step of a parameter, as `parameters::Info` holds them. */
function plain(parameter: ResolvedParameter) {
  switch (parameter.type) {
    case 'boolean':
      return {
        min: 0,
        max: 1,
        default: parameter.default ? 1 : 0,
        step: 0,
        unit: '',
      };
    case 'choice':
      return {
        min: 0,
        max: parameter.options.length - 1,
        default: parameter.options.findIndex(
          (option) => option.value === parameter.default,
        ),
        step: 0,
        unit: '',
      };
    default:
      return {
        min: parameter.min,
        max: parameter.max,
        default: parameter.default,
        step: parameter.step ?? 0,
        unit: parameter.unit ?? '',
      };
  }
}

function renderInfo(parameter: ResolvedParameter): string {
  const p = plain(parameter);
  const choices =
    parameter.type === 'choice'
      ? parameter.options
          .map(
            (option) =>
              `{ ${cppString(option.value)}, ${cppString(option.label)} }`,
          )
          .join(', ')
      : '';
  return `            { ${cppString(parameter.id)}, ${cppString(parameter.label)}, parameters::Type::${TYPE[parameter.type]}, parameters::Access::${ACCESS[parameter.access]}, ${cppDouble(p.min)}, ${cppDouble(p.max)}, ${cppDouble(p.default)}, ${cppDouble(p.step)}, ${cppString(p.unit)}, { ${choices} } },`;
}

/** The name of a parameter's generated function. */
function fn(parameter: ResolvedParameter, name: string): string {
  return `${parameter.id}_${name}`;
}

function renderFunctions(parameter: ResolvedParameter): string {
  const { semantics } = parameter;
  const type = cppType(semantics.valueType);
  const inputs = semanticsInputs(semantics.valueType);
  const compile = (
    expression: unknown,
    i: Readonly<Record<string, never>> | object,
  ) => compileCpp(expression, i as never);
  return `        // "${parameter.id}"
        double ${fn(parameter, 'toValue')}(double normalized) noexcept
        {
            return static_cast<double>(${compile(semantics.toValue, inputs.toValue)});
        }
        double ${fn(parameter, 'toNormalized')}(double plain) noexcept
        {
            const ${type} value = static_cast<${type}>(plain);
            return ${compile(semantics.toNormalized, inputs.toNormalized)};
        }
        double ${fn(parameter, 'constrain')}(double value) noexcept
        {
            return static_cast<double>(${compile(semantics.constrain, inputs.constrain)});
        }
        std::string ${fn(parameter, 'format')}(double plain)
        {
            const ${type} value = static_cast<${type}>(plain);
            return ${compile(semantics.format, inputs.format)};
        }
        std::optional<double> ${fn(parameter, 'parse')}(std::string_view textView)
        {
            const std::string text(textView);
            const auto value = ${compile(semantics.parse, inputs.parse)};
            if (! value)
                return std::nullopt;
            return static_cast<double>(*value);
        }
`;
}

/**
 * `SoundorParameters.cpp`: in `namespace`, `parameterInfos()` and
 * `parameterBehaviors()`, in the config's order.
 */
export function renderParametersSource(
  parameters: readonly ResolvedParameter[],
  namespace: string,
): string {
  const behaviors = parameters
    .map(
      (parameter) =>
        `            { &${fn(parameter, 'toValue')}, &${fn(parameter, 'toNormalized')}, &${fn(parameter, 'constrain')}, &${fn(parameter, 'format')}, &${fn(parameter, 'parse')} },`,
    )
    .join('\n');
  return `${HEADER}// The parameters of soundor.config: what they are, and what they do.

${CPP_PRAGMAS}
#include <soundor/backend/JuceParameter.h>
#include <soundor/parameters/Parameters.h>

${CPP_INCLUDES.map((header) => `#include ${header}`).join('\n')}
#include <span>
#include <vector>

namespace ${namespace}
{
    namespace
    {
${cppRuntime()
  .split('\n')
  .map((line) => (line === '' ? '' : `        ${line}`))
  .join('\n')}
${parameters.map(renderFunctions).join('\n')}    } // namespace

    // The config's parameters, in the order soundor:parameters indexes them.
    std::span<const parameters::Info> parameterInfos()
    {
        static const std::vector<parameters::Info> infos {
${parameters.map(renderInfo).join('\n') || '            // no parameters'}
        };
        return infos;
    }

    // Their behavior, in the same order.
    std::span<const backend::ParameterBehavior> parameterBehaviors()
    {
        static const std::vector<backend::ParameterBehavior> behaviors {
${behaviors || '            // no parameters'}
        };
        return behaviors;
    }
} // namespace ${namespace}
`;
}
