import {
  describeState,
  stateJson,
  enumeratorName,
  type ResolvedSoundorConfig,
  type NativeType,
  type StateSchema,
} from '@soundor/runtime-sdk';

import {
  valueType,
  renderEnumConversions,
  renderStructConversions,
  readStatement,
  writeExpression,
} from './native-codegen';

const ns = 'soundor::inline SOUNDOR_ABI_NAMESPACE';
const header = '// This file was generated by Soundor. Do not edit.\n';
function cppType(t: NativeType): string {
  if (t.kind === 'declared') return `native::${t.name}`;
  if (t.kind === 'array') return `std::vector<${cppType(t.element)}>`;
  if (t.kind === 'nullable') return `std::optional<${cppType(t.inner)}>`;
  return valueType(t);
}
const quote = (v: string) => JSON.stringify(v);

export function generateStateSources(config: ResolvedSoundorConfig) {
  const schema = describeState(config.state, config.native);
  return [
    { path: 'soundor/SoundorState.h', contents: stateHeader(schema) },
    { path: 'soundor/SoundorState.cpp', contents: stateBindings(schema) },
  ];
}
function stateHeader(schema: StateSchema): string {
  const codecs = schema.types.map((t) => {
    const type = `native::${t.name}`;
    if (t.kind === 'enum')
      return `template <> struct StateCodec<${type}> {
      static juce::var encode(${type} value) {
        switch(value) { ${t.values.map((v) => `case ${type}::${enumeratorName(v)}: return juce::String(${quote(v)});`).join(' ')} }
        throw std::invalid_argument("invalid enum state");
      }
      static ${type} decode(const juce::var& value) {
        if (!value.isString()) throw std::invalid_argument("expected enum state");
        ${t.values.map((v) => `if (value.toString() == ${quote(v)}) return ${type}::${enumeratorName(v)};`).join('\n')}
        throw std::invalid_argument("invalid enum state");
      }
    };`;
    return `template <> struct StateCodec<${type}> {
      static juce::var encode(const ${type}& value) {
        juce::var result(new juce::DynamicObject());
        auto* out = result.getDynamicObject();
        ${t.fields.map((f) => `out->setProperty(${quote(f.name)}, StateCodec<${cppType(f.type)}>::encode(value.${f.name}));`).join('\n')}
        return result;
      }
      static ${type} decode(const juce::var& value) {
        auto* object = value.getDynamicObject();
        if (object == nullptr || object->getProperties().size() != ${t.fields.length}) throw std::invalid_argument("invalid struct state: ${t.name}");
        ${type} out;
        ${t.fields.map((f) => `if (!object->hasProperty(${quote(f.name)})) throw std::invalid_argument("missing state field: ${f.name}");\n        out.${f.name} = StateCodec<${cppType(f.type)}>::decode(object->getProperty(${quote(f.name)}));`).join('\n')}
        return out;
      }
    };`;
  });
  return `${header}#pragma once
#include <soundor/backend/JuceState.h>
#include <soundor/native/SoundorNative.h>
namespace ${ns}::backend { ${codecs.join('\n')} }
namespace ${ns} {
  class PersistentState {
    backend::StateStore store;
  public:
    explicit PersistentState(history::StateHistory* history = nullptr) : store(history)${schema.fields.length ? ', ' : ''}${schema.fields.map((f) => `${f.name}(store, ${quote(f.name)}, backend::StateCodec<${cppType(f.type)}>::decode(backend::parseStateJson(${quote(stateJson(f.default))})))`).join(', ')} {}
    ${schema.fields.map((f) => `backend::StateField<${cppType(f.type)}> ${f.name};`).join('\n')}
    backend::StateStore& storage() { return store; }
    juce::var snapshot() const {
      juce::var result(new juce::DynamicObject());
        auto* out = result.getDynamicObject();
      for (const auto& [name, value] : store.snapshot()) out->setProperty(juce::Identifier(name), backend::parseStateJson(value));
      return result;
    }
    static backend::StateStore::Values prepare(const juce::var& data) {
      if (data.getDynamicObject() == nullptr) throw std::invalid_argument("expected state object");
      backend::StateStore::Values out;
      ${schema.fields
        .map(
          (f) => `{
        auto raw = data.hasProperty(${quote(f.name)}) ? data[${quote(f.name)}] : backend::parseStateJson(${quote(stateJson(f.default))});
        auto value = backend::StateCodec<${cppType(f.type)}>::decode(raw);
        out[${quote(f.name)}] = backend::stateJson(backend::StateCodec<${cppType(f.type)}>::encode(value));
      }`,
        )
        .join('\n')}
      return out;
    }
    void apply(const backend::StateStore::Values& values) {
      store.resetGestures();
      store.replace(values);
      store.restored();
    }
  };
  namespace persistent {
    void install(js::Context&, PersistentState&);
    void dispatch(js::Context&);
  }
}
`;
}
function stateBindings(schema: StateSchema): string {
  const conversions = schema.types
    .map((t) =>
      t.kind === 'enum'
        ? renderEnumConversions(t, true, true)
        : renderStructConversions(t, true, true, true),
    )
    .join('\n');
  return `${header}#include "SoundorState.h"
#include "js/Bindings.h"
#include "modules/history/HistoryBindings.h"
#include <list>
namespace ${ns}::persistent {
namespace {
  namespace bind = js::bind;
  using namespace native;
  using bind::read;
  using bind::write;
${conversions}
  const char bindingKey = 0;
  struct Listener { std::string field; bool active = true; };
  struct Cache { std::string json; };
  struct Binding {
    explicit Binding(PersistentState& owner) : state(owner), session(state.storage().connect()) {}
    ~Binding() { state.storage().disconnect(session); }
    PersistentState& state;
    backend::StateStore::Session session;
    std::list<Listener> listeners;
    std::map<std::string, Cache> caches;
  };
  Binding& binding(bind::ContextState& ctx) { return *bind::contextData<Binding>(ctx, &bindingKey); }
  void validateInput(bind::ContextState& ctx, const jsi::Value& value, std::size_t depth, std::size_t& budget) {
    if (depth > 64 || budget == 0) bind::throwRangeError(ctx, "state value exceeds resource limits");
    --budget;
    if (value.isString()) {
      const auto text = value.getString(ctx.rt).utf16(ctx.rt);
      for (std::size_t i = 0; i < text.size(); ++i) {
        const auto c = text[i];
        if (c == 0 || (c >= 0xdc00 && c <= 0xdfff)) bind::throwTypeError(ctx, "invalid Unicode state string");
        if (c >= 0xd800 && c <= 0xdbff) {
          if (++i >= text.size() || text[i] < 0xdc00 || text[i] > 0xdfff) bind::throwTypeError(ctx, "invalid Unicode state string");
        }
      }
    } else if (value.isObject()) {
      const auto object = value.getObject(ctx.rt);
      if (object.isArray(ctx.rt) && object.getArray(ctx.rt).size(ctx.rt) > budget) bind::throwRangeError(ctx, "state array exceeds resource limits");
      const auto names = object.getPropertyNames(ctx.rt);
      if (names.size(ctx.rt) > budget) bind::throwRangeError(ctx, "state object exceeds resource limits");
      for (std::size_t i = 0; i < names.size(ctx.rt); ++i) validateInput(ctx, object.getProperty(ctx.rt, names.getValueAtIndex(ctx.rt, i).getString(ctx.rt)), depth + 1, budget);
    }
  }
  jsi::Value freeze(bind::ContextState& ctx, jsi::Value value) {
    if (!value.isObject()) return value;
    auto object = value.getObject(ctx.rt);
    auto names = object.getPropertyNames(ctx.rt);
    for (std::size_t i = 0; i < names.size(ctx.rt); ++i) {
      const auto name = names.getValueAtIndex(ctx.rt, i).getString(ctx.rt);
      auto child = object.getProperty(ctx.rt, name);
      if (child.isObject()) static_cast<void>(freeze(ctx, std::move(child)));
    }
    auto constructor = ctx.rt.global().getPropertyAsObject(ctx.rt, "Object");
    return constructor.getPropertyAsFunction(ctx.rt, "freeze").call(ctx.rt, object);
  }
  jsi::Value subscribe(bind::ContextState& ctx, std::string field, const jsi::Value* args, std::size_t count) {
    if (count != 1 || !bind::isFunction(ctx, args[0])) bind::throwTypeError(ctx, "subscribe expects a function");
    auto& entry = binding(ctx).listeners.emplace_back(std::move(field), true);
    bind::retainValue(ctx, &entry, jsi::Value(ctx.rt, args[0]));
    return bind::closure(ctx, "unsubscribe", 0, [entry = &entry](auto& context, const auto&, const auto*, auto) {
      entry->active = false;
      bind::retainValue(context, entry, jsi::Value::undefined());
      return jsi::Value::undefined();
    });
  }
  jsi::Value valueFor(bind::ContextState& ctx, const std::string& field, const std::string& json) {
    auto& cache = binding(ctx).caches[field];
    if (cache.json != json || bind::retainedValue(ctx, &cache) == nullptr) {
      jsi::Value value;
      ${schema.fields
        .map(
          (f) => `if (field == ${quote(f.name)}) {
        auto nativeValue = backend::StateCodec<${cppType(f.type)}>::decode(backend::parseStateJson(json));
        value = ${writeExpression(f.type, 'ctx', 'nativeValue')};
      }`,
        )
        .join('\n')}
      bind::retainValue(ctx, &cache, freeze(ctx, std::move(value)));
      cache.json = json;
    }
    return jsi::Value(ctx.rt, *bind::retainedValue(ctx, &cache));
  }
}
void install(js::Context& context, PersistentState& state) {
  bind::setContextData(context, &bindingKey, std::make_shared<Binding>(state));
  js::registerNativeModule(context, "soundor:state", { [](bind::ContextState& ctx, jsi::Object& exports) {
    bind::ObjectBuilder fields(ctx);
    ${schema.fields
      .map(
        (f) => `{
      bind::ObjectBuilder field(ctx);
      field.set("get", bind::closure(ctx, "get", 0, [](auto& c, const auto&, const auto*, auto) {
        return bind::invoke(c, "state.${f.name}.get", [&] { return valueFor(c, ${quote(f.name)}, binding(c).state.storage().get(${quote(f.name)})); });
      }));
      field.set("set", bind::closure(ctx, "set", 1, [](auto& ctx, const auto&, const auto* args, auto count) {
        return bind::invoke(ctx, "state.${f.name}.set", [&] { return history::invoke(ctx, binding(ctx).state.storage().historyManager(), [&]() -> jsi::Value {
          if (count < 1 || count > 2) bind::throwTypeError(ctx, "set expects a value and optional History options");
          const auto options = history::readOptions(ctx, args, count, 1);
          auto resolved = jsi::Value(ctx.rt, args[0]);
          if (bind::isFunction(ctx, resolved)) {
            auto current = valueFor(ctx, ${quote(f.name)}, binding(ctx).state.storage().get(${quote(f.name)}));
            resolved = resolved.getObject(ctx.rt).getFunction(ctx.rt).call(ctx.rt, current);
          }
          if (resolved.isObject() && bind::isFunction(ctx, resolved.getObject(ctx.rt).getProperty(ctx.rt, "then")))
            bind::throwTypeError(ctx, "Setters require synchronous values, not promises or thenables");
          std::size_t budget = 100000;
          validateInput(ctx, resolved, 0, budget);
          const bind::Path path { "state.${f.name}" };
          ${cppType(f.type)} value {};
          ${readStatement(f.type, 'ctx', 'resolved', 'path', 'value', false)};
          binding(ctx).state.${f.name}.set(std::move(value), options);
          return jsi::Value::undefined();
        }); });
      }));
      ${['beginGesture', 'endGesture']
        .map(
          (
            method,
          ) => `field.set("${method}", bind::closure(ctx, "${method}", 0, [](auto& c, const auto&, const auto* args, auto count) {
        return bind::invoke(c, "state.${f.name}.${method}", [&] { return history::invoke(c, binding(c).state.storage().historyManager(), [&]() -> jsi::Value {
          ${method === 'beginGesture' ? 'if (count > 1) bind::throwTypeError(c, "beginGesture expects optional History options");' : 'bind::expectArgumentCount(c, "endGesture", count, 0);'}
          auto& view = binding(c);
          view.state.storage().${method}(${quote(f.name)}, view.session${method === 'beginGesture' ? ', history::readOptions(c, args, count, 0)' : ''});
          return jsi::Value::undefined();
        }); });
      }));`,
        )
        .join('\n')}
      field.set("subscribe", bind::closure(ctx, "subscribe", 1, [](auto& c, const auto&, const auto* args, auto count) {
        return bind::invoke(c, "state.subscribe", [&] { return subscribe(c, ${quote(f.name)}, args, count); });
      }));
      fields.set(${quote(f.name)}, freeze(ctx, field.release()));
    }`,
      )
      .join('\n')}
    fields.set("onRestored", bind::closure(ctx, "onRestored", 1, [](auto& c, const auto&, const auto* args, auto count) {
      return bind::invoke(c, "state.onRestored", [&] { return subscribe(c, "", args, count); });
    }));
    bind::setProperty(ctx, exports, "state", freeze(ctx, fields.release()));
  }, {}, {} });
}
void dispatch(js::Context& context) {
  auto& ctx = js::stateOf(context);
  auto* view = bind::contextData<Binding>(ctx, &bindingKey);
  if (view == nullptr || ctx.halted()) return;
  for (const auto& event : view->state.storage().drain()) {
    const auto field = event.restored ? std::string() : event.field;
    std::vector<const Listener*> entries;
    for (const auto& entry : view->listeners) if (entry.active && entry.field == field) entries.push_back(&entry);
    // Nobody listens to the field: its value is not converted.
    if (entries.empty()) continue;
    const auto value = event.restored ? jsi::Value::undefined() : valueFor(ctx, field, event.value);
    for (const auto* entry : entries) {
      const auto* retained = bind::retainedValue(ctx, entry);
      if (!entry->active || retained == nullptr || !bind::isFunction(ctx, *retained)) continue;
      auto function = retained->getObject(ctx.rt).getFunction(ctx.rt);
      const jsi::Value args[] = { jsi::Value(ctx.rt, value) };
      bind::call(ctx, function, jsi::Value::undefined(), event.restored ? std::span<const jsi::Value>() : std::span<const jsi::Value>(args), "state subscriber failed");
    }
  }
}
}
`;
}

export function persistentProcessorSource(
  parameters: ResolvedSoundorConfig['parameters'],
): string {
  const encode = parameters
    .map((p) => {
      const raw = `static_cast<float>(parameterTree.getChildWithProperty("id", ${quote(p.id)})["value"])`;
      const value =
        p.type === 'boolean'
          ? `${raw} >= 0.5f`
          : p.type === 'choice'
            ? `juce::StringArray { ${p.options.map((o) => quote(o.value)).join(', ')} }[static_cast<int>(${raw})]`
            : `static_cast<double>(${raw})`;
      return `values->setProperty(${quote(p.id)}, ${value});`;
    })
    .join('\n');
  const decode = parameters
    .map((p) => {
      const initial =
        p.type === 'boolean'
          ? String(p.default)
          : p.type === 'choice'
            ? `juce::String(${quote(p.default)})`
            : String(p.default);
      const plain =
        p.type === 'boolean'
          ? `if (!value.isBool()) throw std::invalid_argument("parameters.${p.id}: expected boolean");\n      const float plain = static_cast<bool>(value) ? 1.0f : 0.0f;`
          : p.type === 'choice'
            ? `if (!value.isString()) throw std::invalid_argument("parameters.${p.id}: expected choice");\n      const int index = juce::StringArray { ${p.options.map((o) => quote(o.value)).join(', ')} }.indexOf(value.toString());\n      if (index < 0) throw std::invalid_argument("parameters.${p.id}: invalid choice");\n      const float plain = static_cast<float>(index);`
            : `if (!value.isInt() && !value.isInt64() && !value.isDouble()) throw std::invalid_argument("parameters.${p.id}: expected number");\n      const double number = static_cast<double>(value);\n      if (!std::isfinite(number) || number < ${p.min} || number > ${p.max}${p.type !== 'float32' ? ' || std::trunc(number) != number' : ''}) throw std::invalid_argument("parameters.${p.id}: invalid number");\n      const float plain = static_cast<float>(number);`;
      return `{
      const auto value = saved.hasProperty(${quote(p.id)}) ? saved[${quote(p.id)}] : juce::var(${initial});
      ${plain}
      juce::ValueTree child("PARAM");
      child.setProperty("id", ${quote(p.id)}, nullptr);
      child.setProperty("value", plain, nullptr);
      tree.addChild(child, -1, nullptr);
    }`;
    })
    .join('\n');
  return `
    AudioProcessor::~AudioProcessor() { cancelPendingUpdate(); }

    void AudioProcessor::getStateInformation(juce::MemoryBlock& destData)
    {
        const std::lock_guard historyGuard(stateHistory.mutex());
        const std::lock_guard guard(state.storage().mutex());
        // APVTS flushes pending parameter changes before we copy them.
        const auto parameterTree = parameters->copyState();
        juce::var parameterValues(new juce::DynamicObject());
        auto* values = parameterValues.getDynamicObject();
        ${encode}
        juce::var document(new juce::DynamicObject());
        auto* root = document.getDynamicObject();
        root->setProperty("version", 1);
        root->setProperty("parameters", parameterValues);
        root->setProperty("state", state.snapshot());
        const auto json = backend::stateJson(document);
        const auto bytes = json.size();
        if (bytes > backend::maxSnapshotBytes) { juce::Logger::writeToLog("Soundor snapshot exceeds 8 MiB"); return; }
        destData.replaceAll(json.data(), bytes);
    }

    void AudioProcessor::setStateInformation(const void* data, int sizeInBytes)
    {
      try {
        if (data == nullptr || sizeInBytes <= 0 || static_cast<std::size_t>(sizeInBytes) > backend::maxSnapshotBytes)
          throw std::invalid_argument("invalid Soundor snapshot size");
        backend::checkLegacyXml(data, sizeInBytes);
        juce::var saved;
        juce::var persistent(new juce::DynamicObject());
        if (auto xml = getXmlFromBinary(data, sizeInBytes)) {
          if (!xml->hasTagName("SOUNDOR")) throw std::invalid_argument("unsupported legacy Soundor state");
          const auto legacy = juce::ValueTree::fromXml(*xml);
          juce::var parameterValues(new juce::DynamicObject());
        auto* values = parameterValues.getDynamicObject();
          for (const auto& child : legacy) {
            const auto id = child["id"].toString();
            const auto raw = child["value"];
            const auto decimal = raw.toString().toStdString();
            const double number = backend::parseStateNumber(decimal);
            values->setProperty(id, number);
          }
          saved = parameterValues;
          ${parameters
            .filter((p) => p.type === 'boolean' || p.type === 'choice')
            .map((p) =>
              p.type === 'boolean'
                ? `if (saved.hasProperty(${quote(p.id)})) { const double number = static_cast<double>(saved[${quote(p.id)}]); if (number != 0 && number != 1) throw std::invalid_argument("invalid legacy boolean"); saved.getDynamicObject()->setProperty(${quote(p.id)}, number == 1); }`
                : `if (saved.hasProperty(${quote(p.id)})) {
            const double index = static_cast<double>(saved[${quote(p.id)}]);
            if (index < 0 || index >= ${p.options.length} || std::floor(index) != index) throw std::invalid_argument("invalid legacy choice");
            saved.getDynamicObject()->setProperty(${quote(p.id)}, juce::StringArray { ${p.options.map((o) => quote(o.value)).join(', ')} }[static_cast<int>(index)]);
          }`,
            )
            .join('\n')}
        } else {
          const auto text = juce::String::fromUTF8(static_cast<const char*>(data), sizeInBytes);
          const auto root = backend::parseStateJson(text.toStdString());
          if (root.getDynamicObject() == nullptr || (!root["version"].isInt() && !root["version"].isInt64() && !root["version"].isDouble()) || static_cast<double>(root["version"]) != 1 || root.getDynamicObject()->getProperties().size() != 3)
            throw std::invalid_argument("invalid or unsupported Soundor snapshot");
          saved = root["parameters"];
          persistent = root["state"];
        }
        if (saved.getDynamicObject() == nullptr) throw std::invalid_argument("expected parameters object");
        auto prepared = PersistentState::prepare(persistent);
        juce::ValueTree tree("SOUNDOR");
        ${decode}
        {
          const std::lock_guard guard(restorationMutex);
          if (restorations.size() >= 8) throw std::length_error("Soundor restoration queue is full");
          restorations.push_back({std::move(tree), std::move(prepared)});
        }
        if (juce::MessageManager::getInstance()->isThisTheMessageThread()) handleAsyncUpdate();
        else triggerAsyncUpdate();
      } catch (const std::exception& error) {
        juce::Logger::writeToLog(juce::String("Soundor state rejected: ") + error.what());
      }
    }

    void AudioProcessor::handleAsyncUpdate()
    {
      if (deliveringRestorations) return;
      const juce::ScopedValueSetter<bool> deliveryGuard(deliveringRestorations, true);
      for (;;) {
        std::optional<Restoration> next;
        {
          const std::lock_guard guard(restorationMutex);
          if (restorations.empty()) break;
          next = std::move(restorations.front());
          restorations.pop_front();
        }
        const std::lock_guard historyGuard(stateHistory.mutex());
        const std::lock_guard guard(state.storage().mutex());
        parameters->replaceState(next->parameters);
        state.apply(next->state);
        stateHistory.clear();
        try { stateRestored(); }
        catch (const std::exception& error) { juce::Logger::writeToLog(juce::String("Soundor stateRestored hook failed: ") + error.what()); }
        catch (...) { juce::Logger::writeToLog("Soundor stateRestored hook failed"); }
      }
    }
`;
}
