/**
 * Generates the C++ side of `soundor:native` from the config's native API:
 *
 * - `soundor/native/SoundorNative.h` — the types (structs and enums) and the
 *   `NativeApi` interface the plugin implements, plus
 *   `install()`, which makes the module importable in a JavaScript context.
 *   Plain C++: no engine headers, so plugin code including it never sees
 *   Hermes.
 * - `soundor/native/SoundorNative.cpp` — the bindings (on Hermes's JSI):
 *   argument validation, conversions, exception and promise plumbing,
 *   written against the runtime's internal `js/Bindings.h` helpers.
 *
 * Output is deterministic and readable but not run through clang-format; like
 * all generated code it is excluded from the format and lint checks, and is
 * never edited by hand.
 */

import type {
  NativeApiModel,
  NativeChannelModel,
  NativeEventModel,
  NativeField,
  NativeMethodModel,
  NativeType,
  NativeTypeModel,
  PrimitiveTypeName,
} from '@soundor/runtime-sdk';
import { enumeratorName } from '@soundor/runtime-sdk';

export interface NativeCodegenFile {
  readonly path: string;
  readonly contents: string;
}

const HEADER = '// This file was generated by Soundor. Do not edit.\n';
const NAMESPACE = 'soundor::inline SOUNDOR_ABI_NAMESPACE::native';

/** Each primitive's C++ type: exact widths and signedness. */
const PRIMITIVE_TYPES: Record<PrimitiveTypeName, string> = {
  boolean: 'bool',
  string: 'std::string',
  int8: 'std::int8_t',
  uint8: 'std::uint8_t',
  int16: 'std::int16_t',
  uint16: 'std::uint16_t',
  int32: 'std::int32_t',
  uint32: 'std::uint32_t',
  int64: 'std::int64_t',
  uint64: 'std::uint64_t',
  float32: 'float',
  float64: 'double',
};

/** The generated `soundor:native` C++ sources, paths relative to the gen root. */
export function generateNativeModuleSources(
  model: NativeApiModel,
): NativeCodegenFile[] {
  return [
    { path: 'soundor/native/SoundorNative.h', contents: renderHeader(model) },
    { path: 'soundor/native/SoundorNative.cpp', contents: renderSource(model) },
  ];
}

// ── Header ──────────────────────────────────────────────────────────────────

function renderHeader(model: NativeApiModel): string {
  const types = model.types.map(renderTypeDeclaration);
  const methods = model.methods.map(
    (method) => `        virtual ${methodSignature(method)} = 0;`,
  );
  const apiBody = methods.length > 0 ? `\n${methods.join('\n')}` : '';
  const hasEvents = model.events.length > 0;
  const hasChannels = model.channels.length > 0;
  const feeds = [
    ...(hasEvents ? ['`events`'] : []),
    ...(hasChannels ? ['`channels`'] : []),
  ].join(' and ');
  const install =
    feeds.length > 0
      ? `    // Makes \`soundor:native\` importable in \`context\`, backed by \`api\`${model.methods.length === 0 ? '\n    // (nullptr: the config declares no methods)' : ''}, and
    // connects ${feeds} to it. Call before evaluating code that imports
    // it; the context keeps \`api\` alive, and disconnects when it goes.
    void install(${installParameters(model)});`
      : `    // Makes \`soundor:native\` importable in \`context\`, backed by \`api\`. Call
    // before evaluating code that imports it; the context keeps \`api\` alive.
    void install(${installParameters(model)});`;
  return `${HEADER}#pragma once

${[
  '#include <soundor/js/Context.h>',
  ...(hasChannels ? ['#include <soundor/js/Channels.h>'] : []),
  ...(hasEvents ? ['#include <soundor/js/Events.h>'] : []),
].join('\n')}
#include <soundor/js/Promise.h>

#include <cstddef>
#include <cstdint>
#include <memory>
#include <optional>
#include <span>
#include <string>
#include <vector>

namespace ${NAMESPACE}
{
${types.map((type) => `${type}\n\n`).join('')}    // The plugin's native API, declared under \`native.methods\` in
    // soundor.config. Implement it in the plugin and install() it into each
    // JavaScript context; JavaScript calls it through \`soundor:native\`.
    //
    // Methods run on the UI/message thread and must not block it. Buffer
    // arguments (std::span) view the JavaScript typed array and are only
    // valid until the method returns; everything else is a value of its own.
    // Async methods receive a js::Promise to settle later, on the same thread.
    class NativeApi
    {
    public:
        virtual ~NativeApi() = default;${apiBody}
    };
${hasEvents ? `\n${renderEventsDeclaration(model.events)}\n` : ''}${hasChannels ? `\n${renderChannelsDeclaration(model.channels)}\n` : ''}
${install}
} // namespace ${NAMESPACE}
`;
}

/** The C++ struct of an event's value: \`presetLoaded\` → \`events::PresetLoaded\`. */
export function eventStructName(event: NativeEventModel): string {
  return event.name[0]!.toUpperCase() + event.name.slice(1);
}

/** install()'s parameters: the context, the API, then each feed it has. */
function installParameters(model: NativeApiModel): string {
  return [
    'js::Context& context',
    'std::shared_ptr<NativeApi> api',
    ...(model.events.length > 0 ? ['const Events& events'] : []),
    ...(model.channels.length > 0 ? ['const Channels& channels'] : []),
  ].join(', ');
}

/** The C++ type of a channel: \`js::BufferChannel<float>\`, \`js::ValueChannel<double>\`. */
export function channelType(channel: NativeChannelModel): string {
  const element = PRIMITIVE_TYPES[channel.element];
  return channel.kind === 'buffer'
    ? `js::BufferChannel<${element}>`
    : `js::ValueChannel<${element}>`;
}

function renderChannelsDeclaration(
  channels: readonly NativeChannelModel[],
): string {
  const members = channels.map((channel) =>
    channel.kind === 'buffer'
      ? `        ${channelType(channel)} ${channel.name} { ${channel.maxLength} };`
      : `        ${channelType(channel)} ${channel.name};`,
  );
  return `    // The plugin's native channels, declared under \`native.channels\` in
    // soundor.config: values the plugin keeps publishing, of which the UI
    // reads the latest (\`channels\` of \`soundor:native\`). Keep one per plugin
    // instance and install() it into each JavaScript context.
    //
    // Publish from the audio callback if you like: publish(), and a buffer's
    // buffer() and commit(), take no lock, never allocate and never wait.
    // One thread at a time publishes a channel. The UI takes the newest value
    // at its next tick, never a partly written one; values in between are
    // skipped, not queued, so no UI, or a slow one, costs nothing.
    struct Channels
    {
${members.join('\n')}
    };`;
}

function renderEventsDeclaration(events: readonly NativeEventModel[]): string {
  const structs = events.map(
    (event) => `        struct ${eventStructName(event)}
        {
${event.fields.map((field) => `            ${valueType(field.type)} ${field.name} {};\n`).join('')}        };`,
  );
  const publishers = events.map(
    (event) =>
      `        bool ${event.name}(events::${eventStructName(event)} event${event.fields.length === 0 ? ' = {}' : ''}) const;`,
  );
  return `    // The values of the events declared under \`native.events\`.
    namespace events
    {
${structs.join('\n\n')}
    } // namespace events

    // The plugin's native events, declared under \`native.events\` in
    // soundor.config: the plugin publishes them, the UI subscribes to them
    // (\`events\` of \`soundor:native\`). Keep one per plugin instance and
    // install() it into each JavaScript context.
    //
    // Publish from any thread but the audio callback: a publisher copies the
    // value, takes a short lock and returns; it never waits for the UI. Each
    // open UI receives every event published while it is open, on its UI
    // thread at its next tick, in the order they were published. A UI holds
    // at most \`capacity\` undelivered events and drops newer ones; with no UI
    // open, events are dropped. A publisher returns whether a UI took it.
    class Events : public js::EventSource
    {
    public:
        using js::EventSource::EventSource;

${publishers.join('\n')}
    };`;
}

function renderTypeDeclaration(type: NativeTypeModel): string {
  switch (type.kind) {
    case 'enum':
      return `    enum class ${type.name}
    {
${type.values.map((value) => `        ${enumeratorName(value)}, // ${JSON.stringify(value)}`).join('\n')}
    };`;
    case 'struct':
      return `    struct ${type.name}
    {
${type.fields.map((field) => `        ${valueType(field.type)} ${field.name} {};`).join('\n')}
    };`;
  }
}

function methodSignature(method: NativeMethodModel): string {
  const params = method.args.map(
    (arg) => `${argumentType(arg.type)} ${arg.name}`,
  );
  if (method.async) {
    params.push(`js::Promise<${promiseValueType(method.returns)}> promise`);
    return `void ${method.name}(${params.join(', ')})`;
  }
  return `${resultType(method.returns)} ${method.name}(${params.join(', ')})`;
}

/**
 * How a value is passed into a native method: a buffer as a view of the
 * JavaScript typed array, everything else as a value.
 */
function argumentType(type: NativeType): string {
  if (type.kind === 'buffer')
    return `std::span<const ${PRIMITIVE_TYPES[type.element]}>`;
  if (type.kind === 'nullable' && type.inner.kind === 'buffer')
    return `std::optional<${argumentType(type.inner)}>`;
  return valueType(type);
}

/** How a value is returned or stored in a struct. */
export function valueType(type: NativeType): string {
  switch (type.kind) {
    case 'void':
      return 'void';
    case 'primitive':
      return PRIMITIVE_TYPES[type.name];
    case 'buffer':
      return `std::vector<${PRIMITIVE_TYPES[type.element]}>`;
    case 'declared':
      return type.name;
    case 'array':
      return `std::vector<${valueType(type.element)}>`;
    case 'nullable':
      return `std::optional<${valueType(type.inner)}>`;
  }
}

function resultType(type: NativeType): string {
  return valueType(type);
}

function promiseValueType(type: NativeType): string {
  return type.kind === 'void' ? 'void' : valueType(type);
}

// ── Source ──────────────────────────────────────────────────────────────────

function renderSource(model: NativeApiModel): string {
  const enums = model.types.filter((type) => type.kind === 'enum');
  const structs = model.types.filter((type) => type.kind === 'struct');

  const { reads, writes } = conversionUsage(model);
  const sections = [
    `        // Identifies this context's NativeApi in its module data.
        const char apiKey = 0;`,
    ...enums.map((type) =>
      renderEnumConversions(type, reads.has(type.name), writes.has(type.name)),
    ),
    ...structs.map((type) =>
      renderStructConversions(
        type,
        reads.has(type.name),
        writes.has(type.name),
      ),
    ),
    ...model.methods.flatMap((method) =>
      method.async && method.returns.kind !== 'void'
        ? [renderResolver(method), renderBinding(method)]
        : [renderBinding(method)],
    ),
    ...(model.events.length > 0 ? [renderEventDelivery(model.events)] : []),
    ...(model.channels.length > 0 ? [renderChannelNames(model.channels)] : []),
  ];

  const hasEvents = model.events.length > 0;
  const hasChannels = model.channels.length > 0;
  const exportSetters = [
    ...model.methods.map(
      (method) =>
        `bind::setProperty(ctx, exports, ${JSON.stringify(method.name)}, bind::function(ctx, ${JSON.stringify(method.name)}, ${method.args.length}, ${bindingName(method)}));`,
    ),
    ...(hasEvents
      ? ['bind::installEvents(ctx, exports, eventNames, &eventsKey);']
      : []),
    ...(hasChannels
      ? ['bind::installChannels(ctx, exports, channelNames, &channelsKey);']
      : []),
  ];
  const connections = [
    ...(hasEvents
      ? ['        bind::connectEvents(context, events, deliverEvent);']
      : []),
    ...(hasChannels
      ? [
          `        bind::connectChannels(context, { ${model.channels.map((channel) => `channels.${channel.name}.core()`).join(', ')} }, &channelsKey);`,
        ]
      : []),
  ];
  const initializeParams =
    exportSetters.length > 0
      ? 'bind::ContextState& ctx, jsi::Object& exports'
      : 'bind::ContextState&, jsi::Object&';

  return `${HEADER}#include "SoundorNative.h"

#include "js/Bindings.h"

#include <array>
#include <stdexcept>
#include <string_view>
#include <utility>

namespace ${NAMESPACE}
{
    namespace
    {
        using js::bind::read;
        using js::bind::write;
        namespace bind = js::bind;

${sections.join('\n\n')}
    } // namespace

${hasEvents ? `${model.events.map(renderPublisher).join('\n\n')}\n\n` : ''}    void install(${installParameters(model)})
    {
${
  connections.length > 0 && model.methods.length === 0
    ? ''
    : `        if (api == nullptr)
            throw std::invalid_argument("soundor:native needs a NativeApi implementation");
`
}        bind::setContextData(context, &apiKey, std::move(api));${connections.map((line) => `\n${line}`).join('')}
        js::registerNativeModule(context, "soundor:native",
                                 {
                                     [](${initializeParams})
                                     {${exportSetters.map((setter) => `\n                                         ${setter}`).join('')}
                                     },
                                     {},
                                     {},
                                 });
    }
} // namespace ${NAMESPACE}
`;
}

/**
 * Which declared types are converted from JavaScript (arguments) and which to
 * JavaScript (results), following struct fields. Only those conversions are
 * generated, so the output has no unused functions.
 */
function conversionUsage(model: NativeApiModel): {
  reads: Set<string>;
  writes: Set<string>;
} {
  const structs = new Map(
    model.types.flatMap((type) =>
      type.kind === 'struct' ? [[type.name, type] as const] : [],
    ),
  );
  const mark = (type: NativeType, into: Set<string>): void => {
    if (type.kind === 'array') return mark(type.element, into);
    if (type.kind === 'nullable') return mark(type.inner, into);
    if (type.kind !== 'declared' || into.has(type.name)) return;
    into.add(type.name);
    for (const field of structs.get(type.name)?.fields ?? [])
      mark(field.type, into);
  };
  const reads = new Set<string>();
  const writes = new Set<string>();
  for (const method of model.methods) {
    for (const arg of method.args) mark(arg.type, reads);
    mark(method.returns, writes);
  }
  for (const event of model.events)
    for (const field of event.fields) mark(field.type, writes);
  return { reads, writes };
}

export function renderEnumConversions(
  type: Extract<NativeTypeModel, { kind: 'enum' }>,
  readable: boolean,
  writable: boolean,
): string {
  const values = `k${type.name}Values`;
  const parts = [
    `        constexpr std::array<std::string_view, ${type.values.length}> ${values} { ${type.values.map((value) => JSON.stringify(value)).join(', ')} };`,
  ];
  if (readable) {
    parts.push(`        void read(bind::ContextState& ctx, const jsi::Value& value, const bind::Path& path, ${type.name}& out)
        {
            std::size_t index = 0;
            bind::readEnum(ctx, value, path, ${values}, index);
            out = static_cast<${type.name}>(index);
        }`);
  }
  if (writable) {
    parts.push(`        jsi::Value write(bind::ContextState& ctx, ${type.name} value)
        {
            return bind::writeEnum(ctx, ${values}.at(static_cast<std::size_t>(value)));
        }`);
  }
  return parts.join('\n\n');
}

export function renderStructConversions(
  type: Extract<NativeTypeModel, { kind: 'struct' }>,
  readable: boolean,
  writable: boolean,
  strict = false,
): string {
  const reads = type.fields.map(
    (field) =>
      `            ${readStatement(field.type, 'ctx', `bind::property(ctx, object, ${JSON.stringify(field.name)})`, `path.field(${JSON.stringify(field.name)})`, `out.${field.name}`, false)};`,
  );
  const writes = type.fields.map(
    (field) =>
      `            object.set(${JSON.stringify(field.name)}, ${writeExpression(field.type, 'ctx', `value.${field.name}`)});`,
  );
  const parts: string[] = [];
  if (readable) {
    parts.push(`        void read(bind::ContextState& ctx, const jsi::Value& value, const bind::Path& path, ${type.name}& out)
        {
            const jsi::Object object = bind::expectObject(ctx, value, path);${strict ? `\n            if (object.getPropertyNames(ctx.rt).size(ctx.rt) != ${type.fields.length}) bind::throwTypeError(ctx, path.toString() + ": unexpected struct fields");` : ''}
${reads.join('\n')}
        }`);
  }
  if (writable) {
    parts.push(`        jsi::Value write(bind::ContextState& ctx, ${type.name} value)
        {
            bind::ObjectBuilder object(ctx);
${writes.join('\n')}
            return object.release();
        }`);
  }
  return parts.join('\n\n');
}

/**
 * The events' JavaScript side: their names, each value's conversion, and the
 * function js::deliverEvents() calls with each one published.
 */
function renderEventDelivery(events: readonly NativeEventModel[]): string {
  const writes = events.map((event) => {
    const type = `events::${eventStructName(event)}`;
    if (event.fields.length === 0)
      return `        jsi::Value write(bind::ContextState& ctx, ${type})
        {
            return bind::ObjectBuilder(ctx).release();
        }`;
    return `        jsi::Value write(bind::ContextState& ctx, ${type} value)
        {
            bind::ObjectBuilder object(ctx);
${event.fields.map((field) => `            object.set(${JSON.stringify(field.name)}, ${writeExpression(field.type, 'ctx', `value.${field.name}`)});`).join('\n')}
            return object.release();
        }`;
  });
  const cases = events.map(
    (event, index) => `            case ${index}:
            {
                // Shared by every context it is delivered to: converted from a copy.
                auto copy = *static_cast<const events::${eventStructName(event)}*>(value);
                bind::dispatchEvent(ctx, &eventsKey, ${index}, write(ctx, std::move(copy)));
                return;
            }`,
  );
  return `        // Identifies this context's event dispatcher among its retained values.
        const char eventsKey = 0;
        // By event number: what each publisher of Events sends.
        constexpr std::array<const char*, ${events.length}> eventNames { ${events.map((event) => JSON.stringify(event.name)).join(', ')} };

${writes.join('\n\n')}

        void deliverEvent(bind::ContextState& ctx, std::uint32_t event, const void* value)
        {
            switch (event)
            {
${cases.join('\n')}
            default:
                return;
            }
        }`;
}

/** The channels' names, by number, as install() connects them. */
function renderChannelNames(channels: readonly NativeChannelModel[]): string {
  return `        // Identifies this context's channel update function among its retained values.
        const char channelsKey = 0;
        // By channel number: the order install() connects them in.
        constexpr std::array<const char*, ${channels.length}> channelNames { ${channels.map((channel) => JSON.stringify(channel.name)).join(', ')} };`;
}

function renderPublisher(event: NativeEventModel, index: number): string {
  const type = `events::${eventStructName(event)}`;
  return `    bool Events::${event.name}(${type} event) const
    {
        return publish(${index}, std::make_shared<const ${type}>(std::move(event)));
    }`;
}

function renderResolver(method: NativeMethodModel): string {
  const type = valueType(method.returns);
  return `        void ${resolverName(method)}(js::detail::PendingPromise& pending, ${type}&& value)
        {
            bind::resolvePromise(pending, [&](bind::ContextState& ctx) { return ${writeExpression(method.returns, 'ctx', 'value')}; });
        }`;
}

function renderBinding(method: NativeMethodModel): string {
  const name = JSON.stringify(method.name);
  const reads = method.args.map((arg, index) => renderArgumentRead(arg, index));
  const callArgs = method.args.map(
    (arg) => `std::move(${argumentVariable(arg)})`,
  );
  const call = `api->${method.name}(${[...callArgs, ...(method.async ? ['promiseHandle'] : [])].join(', ')})`;

  let tail: string;
  if (method.async) {
    const promiseType = `js::Promise<${promiseValueType(method.returns)}>`;
    const resolver =
      method.returns.kind === 'void'
        ? 'bind::resolvePromiseWithUndefined'
        : resolverName(method);
    tail = `                std::shared_ptr<js::detail::PendingPromise> pending;
                jsi::Value promise = bind::newPromise(ctx, ${name}, pending);
                const ${promiseType} promiseHandle(pending, ${resolver});
                bind::startAsync(*pending, [&] { ${call}; });
                return promise;`;
  } else if (method.returns.kind === 'void') {
    tail = `                ${call};
                return jsi::Value::undefined();`;
  } else {
    tail = `                return ${writeExpression(method.returns, 'ctx', call, true)};`;
  }

  const pathLine =
    method.args.length > 0
      ? `                const bind::Path call { ${name} };\n`
      : '';
  const argvName = method.args.length > 0 ? ' argv' : '';
  return `        jsi::Value ${bindingName(method)}(bind::ContextState& ctx, const jsi::Value&, const jsi::Value*${argvName}, std::size_t count)
        {
            return bind::invoke(ctx, ${name},
                                [&]() -> jsi::Value
                                {
                auto* api = bind::contextData<NativeApi>(ctx, &apiKey);
                if (api == nullptr)
                    bind::throwInternalError(ctx, "soundor:native is not installed in this context");
                bind::expectArgumentCount(ctx, ${name}, count, ${method.args.length});
${pathLine}${reads.join('\n')}${reads.length > 0 ? '\n' : ''}${tail}
                                });
        }`;
}

function renderArgumentRead(arg: NativeField, index: number): string {
  const variable = argumentVariable(arg);
  return `                ${argumentType(arg.type)} ${variable} {};
                ${readStatement(arg.type, 'ctx', `argv[${index}]`, `call.field(${JSON.stringify(arg.name)})`, variable, true)};`;
}

/**
 * A C++ call reading `value` at `path` into `out`; it throws on a mismatch. A
 * buffer is borrowed (a span) where `borrow` is set, a method's own argument,
 * and copied (a vector) elsewhere.
 */
export function readStatement(
  type: NativeType,
  ctx: string,
  value: string,
  path: string,
  out: string,
  borrow: boolean,
): string {
  switch (type.kind) {
    case 'buffer':
      return borrow
        ? `read(${ctx}, ${value}, ${path}, ${out})`
        : `bind::readBuffer(${ctx}, ${value}, ${path}, ${out})`;
    case 'array': {
      const element = valueType(type.element);
      const inner = readStatement(
        type.element,
        'elementCtx',
        'element',
        'elementPath',
        'item',
        false,
      );
      return `bind::readArray(${ctx}, ${value}, ${path}, ${out}, [](bind::ContextState& elementCtx, const jsi::Value& element, const bind::Path& elementPath, ${element}& item) { ${inner}; })`;
    }
    case 'nullable': {
      // Its own names: an array lambda inside it must not shadow them (GCC's
      // -Wshadow).
      const inner = borrow ? argumentType(type.inner) : valueType(type.inner);
      const read = readStatement(
        type.inner,
        'innerCtx',
        'inner',
        'innerPath',
        'present',
        borrow,
      );
      return `bind::readNullable(${ctx}, ${value}, ${path}, ${out}, [](bind::ContextState& innerCtx, const jsi::Value& inner, const bind::Path& innerPath, ${inner}& present) { ${read}; })`;
    }
    case 'primitive':
      // The engine's read() of a double names it a number.
      return type.name === 'float64'
        ? `bind::readFloat64(${ctx}, ${value}, ${path}, ${out})`
        : `read(${ctx}, ${value}, ${path}, ${out})`;
    default:
      return `read(${ctx}, ${value}, ${path}, ${out})`;
  }
}

/**
 * A C++ expression converting `value` (consumed) into a new jsi::Value. A named
 * `value` is moved from; a temporary (a call result) is passed as is.
 */
export function writeExpression(
  type: NativeType,
  ctx: string,
  value: string,
  temporary = false,
): string {
  const consumed = temporary ? value : `std::move(${value})`;
  switch (type.kind) {
    case 'void':
      return 'jsi::Value::undefined()';
    case 'primitive':
      return `write(${ctx}, ${value})`;
    case 'buffer':
      return `bind::writeBuffer(${ctx}, ${consumed})`;
    case 'declared':
      return `write(${ctx}, ${consumed})`;
    case 'array': {
      const element = valueType(type.element);
      const inner = writeExpression(type.element, 'elementCtx', 'item');
      return `bind::writeArray(${ctx}, ${consumed}, [](bind::ContextState& elementCtx, ${element}&& item) { return ${inner}; })`;
    }
    case 'nullable': {
      const inner = valueType(type.inner);
      const write = writeExpression(type.inner, 'innerCtx', 'present');
      return `bind::writeNullable(${ctx}, ${consumed}, [](bind::ContextState& innerCtx, ${inner}&& present) { return ${write}; })`;
    }
  }
}

function argumentVariable(arg: NativeField): string {
  return `arg_${arg.name}`;
}

function bindingName(method: NativeMethodModel): string {
  return `call_${method.name}`;
}

function resolverName(method: NativeMethodModel): string {
  return `resolve_${method.name}`;
}
