/** Emits the generated JUCE framework (CMake + `soundor::` base classes). */
export function generateJuceSources(
  config: SoundorConfig,
  params: GenerateJuceParams,
): CodegenFile[] {
  // In the config's order, which hosts list them in, as the web host does.
  // Sessions keep their values: VST3 ids are hashes of the parameters' ids.

  if (config.plugin.kind === 'midiEffect' && config.audio === undefined)
    config = {
      ...config,
      audio: { buses: {}, layouts: { midi: {} }, defaultLayout: 'midi' },
    };
  const parameters = config.parameters;
  const nativeApi = describeNativeApi(config.native);
  if (!nativeApi.ok) {
    // Config validation rejects these first; this guards direct callers.
    throw new Error(
      `Invalid native API: ${nativeApi.issues.map((issue) => `${issue.path}: ${issue.message}`).join('; ')}`,
    );
  }
  return [
    { path: 'setup.cmake', contents: renderSetupCmake(params, config) },
    { path: 'soundor/soundor.h', contents: renderUmbrella() },
    {
      path: 'soundor/SoundorProcessor.h',
      contents: renderProcessorHeader(
        parameters,
        config.plugin,
        nativeApi.model,
        config,
      ),
    },
    {
      path: 'soundor/SoundorProcessor.cpp',
      contents: renderProcessorSource(parameters, config, nativeApi.model),
    },
    {
      path: 'soundor/SoundorParameters.cpp',
      contents: renderParametersSource(parameters, `${NS}::generated`),
    },
    {
      path: 'soundor/SoundorEditor.h',
      contents: renderEditorHeader(resolveEditor(config.editor)),
    },
    {
      path: 'soundor/SoundorEditor.cpp',
      contents: renderEditorSource(
        params.options,
        resolveEditor(config.editor),
        nativeApi.model,
      ),
    },
    ...generateNativeModuleSources(
      nativeApi.model,
      describeController(
        nativeApi.model,
        describeState(config.state, config.native),
        parameters.length,
      ),
    ),
    ...generateStateSources(config),
    ...generatePresetSources(config),
  ].map((file) => ({
    ...file,
    contents: file.contents.replace(/[ \t]+$/gm, ''),
  }));
}

/**
 * The native streams as the Rust processing reaches them: callbacks by
 * index, in the order the Rust SDK numbers them (by name, as the model).
 */
function renderStreamSink(streams: NativeApiModel['streams']): string {
  if (streams.length === 0) return '';
  const cases = (
    kind: 'number' | 'buffer',
    body: (name: string, type: string) => string,
  ) =>
    streams
      .map((stream, index) => ({ stream, index }))
      .filter(({ stream }) => stream.kind === kind)
      .map(
        ({ stream, index }) =>
          `                case ${index}: ${body(stream.name, streamType(stream))}`,
      )
      .join('\n');
  return `    namespace
    {
        // Realtime-safe, as the streams are: the Rust processing calls these
        // on the audio thread.
        void publishStream(void* user, std::uint32_t index, double value)
        {
            [[maybe_unused]] auto& streams = *static_cast<native::Streams*>(user);
            switch (index)
            {
${cases('number', (name, type) => `streams.${name}.publish(static_cast<${type.slice(type.indexOf('<') + 1, -1)}>(value)); break;`)}
                default: break;
            }
        }

        void* streamBuffer(void* user, std::uint32_t index, std::uint32_t* capacity)
        {
            [[maybe_unused]] auto& streams = *static_cast<native::Streams*>(user);
            *capacity = 0;
            switch (index)
            {
${cases('buffer', (name) => `{ const auto storage = streams.${name}.buffer(); *capacity = static_cast<std::uint32_t>(storage.size()); return storage.data(); }`)}
                default: return nullptr;
            }
        }

        void commitStream(void* user, std::uint32_t index, std::uint32_t length)
        {
            [[maybe_unused]] auto& streams = *static_cast<native::Streams*>(user);
            switch (index)
            {
${cases('buffer', (name) => `streams.${name}.commit(length); break;`)}
                default: break;
            }
        }
    } // namespace
`;
}

/** The editor's install() of soundor:native into each new context. */
function renderNativeInstall(native: NativeApiModel): string {
  const fallback = renderNativeApiInstall(native);
  if (native.methods.length === 0 && native.events.length === 0)
    return fallback;
  const feeds = [...(native.streams.length > 0 ? ['owner.nativeStreams'] : [])];
  // The Rust controller backs the methods when the crate exports one;
  // otherwise the C++ NativeApi, as before.
  return `            if (const auto& controller = owner.rustController(); controller != nullptr && controller->present())
                native::installController(${['context', 'controller', ...feeds].join(', ')});
            else
            {
${fallback.replace(/^/gm, '    ')}
            }`;
}

function renderNativeApiInstall(native: NativeApiModel): string {
  const feeds = [
    ...(native.streams.length > 0 ? ['owner.nativeStreams'] : []),
    ...(native.events.length > 0 ? ['owner.rustController()'] : []),
  ];
  if (feeds.length === 0)
    return `            if (auto api = owner.createNativeApi())
                native::install(context, std::move(api));`;
  // Events and streams need no implementation of methods: there may be none.
  if (native.methods.length === 0)
    return `            native::install(context, owner.createNativeApi(), ${feeds.join(', ')});`;
  return `            if (auto api = owner.createNativeApi())
                native::install(context, std::move(api), ${feeds.join(', ')});`;
}

