import { stateJson, type ResolvedSoundorConfig } from '@soundor/runtime-sdk';
import { cppStringLiteral as quote } from '@soundor/runtime-sdk/expression/cpp';

const ns = 'soundor::inline SOUNDOR_ABI_NAMESPACE';
const header = '// This file was generated by Soundor. Do not edit.\n';

export function generatePresetSources(config: ResolvedSoundorConfig) {
  return [
    { path: 'soundor/SoundorPresets.h', contents: presetHeader() },
    { path: 'soundor/SoundorPresets.cpp', contents: presetSource(config) },
    {
      path: 'soundor/SoundorPresetBindings.cpp',
      contents: presetBindingsSource(),
    },
  ];
}
function presetHeader(): string {
  return `${header}#pragma once
#include <soundor/backend/JuceState.h>
#include <soundor/js/Context.h>
#include <atomic>
#include <span>
namespace ${ns} {
class AudioProcessor;
class FactoryPresets {
public:
  struct Info { std::string id; std::string name; };
  struct Selection {
    std::optional<std::string> factoryId;
    bool modified = false;
    bool operator==(const Selection&) const = default;
  };
  explicit FactoryPresets(AudioProcessor&);
  ~FactoryPresets();
  std::span<const Info> factoryPresets() const;
  // Message thread only. Throws for an unknown id. Recording is opt-in.
  void loadFactory(std::string_view id, const history::Options& options = {});
  Selection snapshot() const;
  std::function<void()> subscribe(std::function<void()>);
  void restored();
  void dispatch();
  // Host program callbacks may arrive off the message thread: only enqueue there.
  void requestProgram(int);
  int currentProgram() const noexcept { return program.load(std::memory_order_relaxed); }
  history::StateHistory& historyManager();
private:
  AudioProcessor& owner;
  backend::StateStore selectionStore;
  backend::StateField<std::optional<std::string>> selected;
  std::function<void()> selectionOff;
  std::vector<std::function<void()>> stateOff;
  mutable std::atomic<bool> dirty { true };
  mutable Selection cached;
  std::atomic<int> program { 0 }, requested { -1 };
  Selection delivered;
  std::map<std::size_t, std::function<void()>> listeners;
  std::size_t nextListener = 0;
  bool matches(std::size_t) const;
  struct Updates;
  std::unique_ptr<Updates> updates;
  void timerTick();
};
namespace factory {
  void install(js::Context&, FactoryPresets&);
  void dispatch(js::Context&);
}
}
`;
}
function presetSource(config: ResolvedSoundorConfig): string {
  const catalog = config.presets ?? [];
  const params = config.parameters;
  const checks = catalog
    .map((preset, index) => {
      const comparisons = Object.entries(preset.parameters).map(
        ([id, value]) => {
          const p = params.find((p) => p.id === id)!;
          const plain =
            p.type === 'choice'
              ? p.options.findIndex((o) => o.value === value)
              : typeof value === 'boolean'
                ? value
                  ? 1
                  : 0
                : value;
          return `std::equal_to<double>{}(owner.parameterEditors[${params.indexOf(p)}]->get(), static_cast<double>(static_cast<float>(${plain})))`;
        },
      );
      comparisons.push(
        ...Object.keys(preset.state).map(
          (id) =>
            `owner.state.storage().get(${quote(id)}) == factoryStateValues()[${index}].at(${quote(id)})`,
        ),
      );
      return `case ${index}: return ${comparisons.join(' && ') || 'true'};`;
    })
    .join('\n');
  const loads = catalog
    .map(
      (preset, index) => `case ${index}: {
    ${Object.entries(preset.parameters)
      .map(([id, value]) => {
        const p = params.find((p) => p.id === id)!;
        const plain =
          p.type === 'choice'
            ? p.options.findIndex((o) => o.value === value)
            : typeof value === 'boolean'
              ? value
                ? 1
                : 0
              : value;
        return `owner.parameterEditors[${params.indexOf(p)}]->set(static_cast<double>(static_cast<float>(${plain})));`;
      })
      .join('\n')}
    ${Object.keys(preset.state)
      .map(
        (id) =>
          `owner.state.storage().set(${quote(id)}, factoryStateValues()[${index}].at(${quote(id)}));`,
      )
      .join('\n')}
    break;
  }`,
    )
    .join('\n');
  return `${header}#include "SoundorPresets.h"
#include "SoundorProcessor.h"
#include <functional>
namespace ${ns} {
struct FactoryPresets::Updates : private juce::Timer, private juce::AudioProcessorParameter::Listener {
  FactoryPresets& parent;
  explicit Updates(FactoryPresets& service) : parent(service) {
    ${params
      .filter((p) => p.access !== 'readOnly')
      .map(
        (p) =>
          `parent.owner.getParameters().getParameter(${quote(p.id)})->addListener(this);`,
      )
      .join('\n')}
    if (!parent.factoryPresets().empty()) startTimerHz(60);
  }
  ~Updates() override {
    stopTimer();
    ${params
      .filter((p) => p.access !== 'readOnly')
      .map(
        (p) =>
          `parent.owner.getParameters().getParameter(${quote(p.id)})->removeListener(this);`,
      )
      .join('\n')}
  }
  void parameterValueChanged(int, float) override { parent.dirty.store(true, std::memory_order_release); }
  void parameterGestureChanged(int, bool) override {}
  void timerCallback() override { parent.timerTick(); }
};
namespace {
  [[maybe_unused]] const std::vector<backend::StateStore::Values>& factoryStateValues() {
    static const std::vector<backend::StateStore::Values> values { ${catalog.map((preset) => `PersistentState::prepare(backend::parseStateJson(${quote(stateJson(preset.state))}))`).join(', ')} };
    return values;
  }
}
FactoryPresets::FactoryPresets(AudioProcessor& processor)
  : owner(processor), selectionStore(&processor.stateHistory), selected(selectionStore, "@factoryPreset", std::nullopt) {
  selectionOff = selected.subscribe([this](const auto& id) {
    int index = 0;
    const auto all = factoryPresets();
    if (id) for (std::size_t i = 0; i < all.size(); ++i) if (all[i].id == *id) index = static_cast<int>(i);
    dirty.store(true, std::memory_order_release);
    program.store(index, std::memory_order_relaxed);
    owner.updateHostDisplay(juce::AudioProcessorListener::ChangeDetails().withProgramChanged(true));
  });

  for (const auto& [field, value] : owner.state.storage().snapshot()) {
    static_cast<void>(value);
    stateOff.push_back(owner.state.storage().subscribe(field, [this](const auto&) { dirty.store(true, std::memory_order_release); }));
  }
  restored();
  delivered = snapshot();
  updates = std::make_unique<Updates>(*this);
}
FactoryPresets::~FactoryPresets() {
  updates.reset(); selectionOff();
  for (const auto& off : stateOff) off();

}
history::StateHistory& FactoryPresets::historyManager() { return owner.stateHistory; }
std::span<const FactoryPresets::Info> FactoryPresets::factoryPresets() const {
  static const std::vector<Info> all { ${catalog.map((p) => `{ ${quote(p.id)}, ${quote(p.name)} }`).join(', ')} };
  return all;
}
// Canonical plain values are compared exactly: every changed stored value is modified.
bool FactoryPresets::matches(std::size_t index) const {
  switch(index) { ${checks} default: return false; }
}
FactoryPresets::Selection FactoryPresets::snapshot() const {
  const std::lock_guard guard(owner.stateHistory.mutex());
  const bool staged = owner.stateHistory.inTransaction();
  if (!dirty.exchange(false, std::memory_order_acq_rel) && !staged) return cached;
  const auto id = selected.get();
  const auto all = factoryPresets();
  if (id) for (std::size_t i = 0; i < all.size(); ++i) if (all[i].id == *id) {
    Selection result { id, !matches(i) };
    if (!staged) cached = result; else dirty.store(true, std::memory_order_release);
    return result;
  }
  if (!staged) cached = {}; else dirty.store(true, std::memory_order_release);
  return {};
}
void FactoryPresets::loadFactory(std::string_view id, const history::Options& options) {
  owner.stateHistory.guard([&] {
    const auto all = factoryPresets();
    const auto found = std::find_if(all.begin(), all.end(), [&](const auto& info) { return info.id == id; });
    if (found == all.end()) throw std::invalid_argument("Unknown factory preset '" + std::string(id) + "'");
    const auto index = static_cast<std::size_t>(found - all.begin());
    owner.stateHistory.transaction(options.label.empty() ? "Load " + found->name : options.label, [&] {
      switch(index) { ${loads} default: break; }
      selected.set(std::string(id));
    }, options.enabled);
  });
}
void FactoryPresets::restored() {
  dirty.store(true, std::memory_order_release);
  const auto all = factoryPresets();
  std::optional<std::string> id;
  for (std::size_t i = 0; i < all.size(); ++i) if (matches(i)) { id = all[i].id; break; }
  selected.set(std::move(id));
}
std::function<void()> FactoryPresets::subscribe(std::function<void()> listener) {
  const auto id = ++nextListener;
  listeners.emplace(id, std::move(listener));
  return [this, id] { listeners.erase(id); };
}
void FactoryPresets::dispatch() {
  if (owner.stateHistory.inTransaction()) return;
  const auto next = snapshot();
  if (next == delivered) return;
  delivered = next;
  const auto callbacks = listeners;
  for (const auto& [id, callback] : callbacks) {
    static_cast<void>(id);
    try { callback(); } catch (...) { continue; }
  }
}
void FactoryPresets::requestProgram(int index) {
  if (index < 0 || static_cast<std::size_t>(index) >= factoryPresets().size()) return;
  auto* manager = juce::MessageManager::getInstanceWithoutCreating();
  if (manager && manager->isThisTheMessageThread()) {
    try { loadFactory(factoryPresets()[static_cast<std::size_t>(index)].id); }
    catch (const std::exception& error) { juce::Logger::writeToLog(error.what()); }
  } else requested.store(index, std::memory_order_release);
}
void FactoryPresets::timerTick() {
  const auto next = requested.exchange(-1, std::memory_order_acq_rel);
  if (next >= 0) {
    try { loadFactory(factoryPresets()[static_cast<std::size_t>(next)].id); }
    catch (const std::exception& error) { juce::Logger::writeToLog(error.what()); }
  }
  if (!listeners.empty()) dispatch();
}
}
`;
}

function presetBindingsSource(): string {
  return `${header}#include "SoundorPresets.h"
#include "js/Bindings.h"
#include "modules/history/HistoryBindings.h"
#include <list>
namespace ${ns} {
namespace factory {
namespace {
  namespace bind = js::bind;
  const char key = 0;
  struct Listener { bool active = true; };
  struct Binding {
    explicit Binding(FactoryPresets& value) : service(value), delivered(value.snapshot()) {}
    FactoryPresets& service;
    FactoryPresets::Selection delivered;
    std::optional<FactoryPresets::Selection> cached;
    std::list<Listener> listeners;
    char snapshotKey = 0, listKey = 0;
  };
  Binding& binding(bind::ContextState& ctx) { return *bind::contextData<Binding>(ctx, &key); }
  jsi::Value freeze(bind::ContextState& ctx, jsi::Value value) {
    return ctx.rt.global().getPropertyAsObject(ctx.rt, "Object").getPropertyAsFunction(ctx.rt, "freeze").call(ctx.rt, value);
  }
  jsi::Value snapshot(bind::ContextState& ctx) {
    auto& view = binding(ctx);
    const auto next = view.service.snapshot();
    if (!view.cached || *view.cached != next) {
      bind::ObjectBuilder object(ctx);
      object.set("factoryId", next.factoryId ? bind::write(ctx, *next.factoryId) : jsi::Value::null());
      object.set("modified", jsi::Value(next.modified));
      bind::retainValue(ctx, &view.snapshotKey, freeze(ctx, object.release()));
      view.cached = next;
    }
    return jsi::Value(ctx.rt, *bind::retainedValue(ctx, &view.snapshotKey));
  }
}
void install(js::Context& context, FactoryPresets& service) {
  bind::setContextData(context, &key, std::make_shared<Binding>(service));
  js::registerNativeModule(context, "soundor:presets", { [](bind::ContextState& ctx, jsi::Object& exports) {
    bind::ObjectBuilder api(ctx), factory(ctx);
    factory.set("list", bind::closure(ctx, "list", 0, [](auto& c, const auto&, const auto*, auto count) {
      return bind::invoke(c, "presets.factory.list", [&]() -> jsi::Value {
        bind::expectArgumentCount(c, "list", count, 0);
        auto& view = binding(c);
        if (bind::retainedValue(c, &view.listKey) == nullptr) {
          const auto all = view.service.factoryPresets();
          jsi::Array array(c.rt, all.size());
          for (std::size_t i = 0; i < all.size(); ++i) {
            bind::ObjectBuilder entry(c); entry.set("id", bind::write(c, all[i].id)); entry.set("name", bind::write(c, all[i].name));
            array.setValueAtIndex(c.rt, i, freeze(c, entry.release()));
          }
          bind::retainValue(c, &view.listKey, freeze(c, std::move(array)));
        }
        return jsi::Value(c.rt, *bind::retainedValue(c, &view.listKey));
      });
    }));
    factory.set("load", bind::closure(ctx, "load", 1, [](auto& c, const auto&, const auto* args, auto count) {
      return bind::invoke(c, "presets.factory.load", [&] { return history::invoke(c, binding(c).service.historyManager(), [&]() -> jsi::Value {
        if (count < 1 || count > 2 || !args[0].isString()) bind::throwTypeError(c, "load expects a factory preset id and optional History options");
        const auto id = args[0].getString(c.rt).utf8(c.rt);
        const auto all = binding(c).service.factoryPresets();
        if (std::none_of(all.begin(), all.end(), [&](const auto& info) { return info.id == id; })) bind::throwTypeError(c, "Unknown factory preset '" + id + "'");
        binding(c).service.loadFactory(id, history::readOptions(c, args, count, 1));
        return jsi::Value::undefined();
      }); });
    }));
    api.set("factory", freeze(ctx, factory.release()));
    api.set("getSnapshot", bind::closure(ctx, "getSnapshot", 0, [](auto& c, const auto&, const auto*, auto count) {
      return bind::invoke(c, "presets.getSnapshot", [&] { bind::expectArgumentCount(c, "getSnapshot", count, 0); return snapshot(c); });
    }));
    api.set("subscribe", bind::closure(ctx, "subscribe", 1, [](auto& c, const auto&, const auto* args, auto count) {
      return bind::invoke(c, "presets.subscribe", [&]() -> jsi::Value {
        if (count != 1 || !bind::isFunction(c, args[0])) bind::throwTypeError(c, "subscribe expects a function");
        auto& listener = binding(c).listeners.emplace_back();
        bind::retainValue(c, &listener, jsi::Value(c.rt, args[0]));
        return bind::closure(c, "unsubscribe", 0, [entry = &listener](auto& view, const auto&, const auto*, auto) {
          entry->active = false; bind::retainValue(view, entry, jsi::Value::undefined()); return jsi::Value::undefined();
        });
      });
    }));
    bind::setProperty(ctx, exports, "presets", freeze(ctx, api.release()));
  }, {}, {} });
}
void dispatch(js::Context& context) {
  auto& ctx = js::stateOf(context);
  auto* view = bind::contextData<Binding>(ctx, &key);
  if (view == nullptr || ctx.halted() || std::none_of(view->listeners.begin(), view->listeners.end(), [](const auto& listener) { return listener.active; })) return;
  const auto next = view->service.snapshot();
  if (next == view->delivered) return;
  view->delivered = next;
  std::vector<const Listener*> listeners;
  for (const auto& listener : view->listeners) if (listener.active) listeners.push_back(&listener);
  for (const auto* listener : listeners) {
    const auto* value = bind::retainedValue(ctx, listener);
    if (listener->active && value && bind::isFunction(ctx, *value)) {
      auto callback = value->getObject(ctx.rt).getFunction(ctx.rt);
      bind::call(ctx, callback, jsi::Value::undefined(), {}, "preset subscriber failed");
    }
  }
}
}
}
`;
}
