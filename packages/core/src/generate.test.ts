import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { createNodeFileSystem, type FileSystemHost } from './filesystem';
import {
  GeneratedFilesOutOfDateError,
  checkGeneratedFiles,
  generateSoundorFiles,
  writeGeneratedFiles,
  type CoreSoundorConfig,
} from './generate';

const config: CoreSoundorConfig = {
  plugin: { id: 'com.example.plugin', name: 'Example' },
  runtimes: [{ id: 'juce' }],
  parameters: [
    {
      type: 'boolean',
      id: 'bypass',
      label: 'Bypass',
      access: 'automatable',
      default: false,
    },
    {
      type: 'float32',
      id: 'gain',
      label: 'Gain',
      access: 'automatable',
      min: 0,
      max: 1,
      default: 0.5,
      step: 0.01,
      unit: 'dB',
    },
    {
      type: 'choice',
      id: 'mode',
      label: 'Mode',
      access: 'manual',
      options: [
        { value: 'mono', label: 'Mono' },
        { value: 'stereo', label: 'Stereo' },
      ],
      default: 'stereo',
    },
    {
      type: 'int32',
      id: 'voices',
      label: 'Voices',
      access: 'readOnly',
      min: 1,
      max: 16,
      default: 4,
    },
  ],
  native: {
    types: { Level: { struct: { peak: 'float32', rms: 'float32' } } },
    methods: {
      measure: { args: { samples: 'buffer<float32>' }, returns: 'Level' },
      reset: {},
    },
  },
};

describe('generateSoundorFiles', () => {
  it('emits deterministic golden files', () => {
    expect(generateSoundorFiles(config)).toEqual([
      {
        path: 'assets.d.ts',
        contents: expect.stringContaining(`declare module '*.ttf' {
  const asset: string;`),
      },
      {
        path: 'globals.d.ts',
        contents: expect.stringContaining('declare function fetch('),
      },
      {
        path: 'native.d.ts',
        contents: `// This file was generated by Soundor. Do not edit.

declare module 'soundor:native' {
  export interface Level {
    peak: number;
    rms: number;
  }

  export function measure(samples: Float32Array): Level;

  export function reset(): void;
}
`,
      },
      {
        path: 'parameters.d.ts',
        contents: expect.stringContaining(
          '  export const parameters: {\n    readonly bypass: Parameter<boolean, { readonly id: "bypass"; readonly label: "Bypass"; readonly access: "automatable"; readonly type: "boolean"; readonly default: false }>;\n    readonly gain: Parameter<number, { readonly id: "gain"; readonly label: "Gain"; readonly access: "automatable"; readonly type: "float32"; readonly min: 0; readonly max: 1; readonly default: 0.5; readonly step: 0.01; readonly unit: "dB" }>;\n    readonly mode: Parameter<"mono" | "stereo", { readonly id: "mode"; readonly label: "Mode"; readonly access: "manual"; readonly type: "choice"; readonly options: readonly [{ readonly value: "mono"; readonly label: "Mono" }, { readonly value: "stereo"; readonly label: "Stereo" }]; readonly default: "stereo" }>;\n    readonly voices: Parameter<number, { readonly id: "voices"; readonly label: "Voices"; readonly access: "readOnly"; readonly type: "int32"; readonly min: 1; readonly max: 16; readonly default: 4 }>;\n  };',
        ),
      },
      {
        path: 'platform.d.ts',
        contents: expect.stringContaining('export const plugin:'),
      },
      {
        path: 'soundor.d.ts',
        contents: `// This file was generated by Soundor. Do not edit.

/// <reference path="./assets.d.ts" />
/// <reference path="./globals.d.ts" />
/// <reference path="./native.d.ts" />
/// <reference path="./parameters.d.ts" />
/// <reference path="./state.d.ts" />
/// <reference path="./state-history.d.ts" />
/// <reference path="./platform.d.ts" />
/// <reference path="./ui.d.ts" />
`,
      },
      {
        path: 'state-history.d.ts',
        contents: expect.stringContaining(
          "declare module 'soundor:state-history'",
        ),
      },
      {
        path: 'state.d.ts',
        contents: expect.stringContaining("declare module 'soundor:state'"),
      },
      {
        path: 'ui.d.ts',
        contents: expect.stringContaining("declare module 'soundor:ui' {"),
      },
      {
        path: 'webgl.d.ts',
        contents: expect.stringContaining('interface WebGL2RenderingContext'),
      },
    ]);
  });

  it('produces the same bytes for semantically identical orderings', () => {
    const reversed: CoreSoundorConfig = {
      plugin: config.plugin,
      parameters: [...config.parameters].reverse(),
      native: {
        methods: { reset: {}, measure: config.native!.methods!['measure']! },
        types: config.native!.types!,
      },
    };

    expect(generateSoundorFiles(reversed)).toEqual(
      generateSoundorFiles(config),
    );
  });
});

describe('generated file writer', () => {
  let root: string;
  let fs: FileSystemHost;
  let outputDir: string;

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'soundor-generate-'));
    fs = createNodeFileSystem(root);
    outputDir = fs.resolve('.soundor', 'generated');
  });

  afterEach(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it('writes generated files idempotently', async () => {
    const files = generateSoundorFiles(config);

    await writeGeneratedFiles(fs, outputDir, files);
    const first = await fs.read(join(outputDir, 'parameters.d.ts'));

    await writeGeneratedFiles(fs, outputDir, files);

    expect(await fs.read(join(outputDir, 'parameters.d.ts'))).toBe(first);
    await expect(checkGeneratedFiles(fs, outputDir, files)).resolves.toEqual([
      { path: 'assets.d.ts', status: 'up-to-date' },
      { path: 'globals.d.ts', status: 'up-to-date' },
      { path: 'native.d.ts', status: 'up-to-date' },
      { path: 'parameters.d.ts', status: 'up-to-date' },
      { path: 'platform.d.ts', status: 'up-to-date' },
      { path: 'soundor.d.ts', status: 'up-to-date' },
      { path: 'state-history.d.ts', status: 'up-to-date' },
      { path: 'state.d.ts', status: 'up-to-date' },
      { path: 'ui.d.ts', status: 'up-to-date' },
      { path: 'webgl.d.ts', status: 'up-to-date' },
    ]);
  });

  it('resolves relative output dirs through the filesystem host', async () => {
    const files = generateSoundorFiles(config);

    await writeGeneratedFiles(fs, '.soundor/generated', files);

    await expect(
      fs.read(join(root, '.soundor', 'generated', 'parameters.d.ts')),
    ).resolves.toContain("declare module 'soundor:parameters'");
  });

  it('reports missing and stale generated files in check mode', async () => {
    const files = generateSoundorFiles(config);
    await writeGeneratedFiles(fs, outputDir, files);
    await fs.write(join(outputDir, 'parameters.d.ts'), 'stale');
    await fs.rm(join(outputDir, 'native.d.ts'));

    await expect(
      checkGeneratedFiles(fs, outputDir, files),
    ).rejects.toMatchObject({
      changes: [
        { path: 'native.d.ts', kind: 'missing' },
        { path: 'parameters.d.ts', kind: 'stale' },
      ],
    } satisfies Partial<GeneratedFilesOutOfDateError>);
  });

  it('rejects unsafe generated file paths', async () => {
    await expect(
      writeGeneratedFiles(fs, outputDir, [
        { path: '../user.ts', contents: '' },
      ]),
    ).rejects.toThrow('Unsafe generated file path');
  });
});
