import type { NativeApiDeclaration } from './native-api';
import { nativeTsType, renderNativeTsType } from './native-dts';
import { describeState } from './state';
import type { StateDeclarations } from './state';

export function renderStateDts(
  state?: StateDeclarations,
  native?: NativeApiDeclaration,
): string {
  const schema = describeState(state, native);
  return `// This file was generated by Soundor. Do not edit.
declare module 'soundor:state' {
${schema.types.map((t) => '  ' + renderNativeTsType(t, 'export ')).join('\n')}
  /** Values are detached and deeply frozen. Equivalent writes do not notify. */
  export interface StateField<T> {
    get(): T;
    /** Sets a value or runs a synchronous updater against the latest immutable value. No automatic gesture. */
    set(value: T | ((current: T) => T)): void;
    /** Starts an optional editing interaction. Nested calls form one gesture; writes remain immediate. */
    beginGesture(): void;
    /** Ends an interaction. Unmatched calls do nothing; gestures never automate the host. */
    endGesture(): void;
    subscribe(listener: (value: T) => void): () => void;
  }
  export const state: {
${schema.fields.map((f) => `    readonly ${f.name}: StateField<${nativeTsType(f.type, 'result')}>;`).join('\n')}
    /** Field notifications precede this callback. Initial hydration is available through get(). */
    onRestored(listener: () => void): () => void;
  };
}
`;
}
