/**
 * Renders the TypeScript declaration of the runtime-provided `soundor:native`
 * module from a {@link NativeApiModel}. The file is an ambient module
 * declaration: plugin code imports from `'soundor:native'` and the bundler
 * leaves the import for the runtime to resolve.
 */

import {
  BUFFER_ARRAY_TYPES,
  type NativeApiModel,
  type NativeType,
  type NativeTypeModel,
} from './native-api';

const HEADER = '// This file was generated by Soundor. Do not edit.\n\n';

export function renderNativeDts(model: NativeApiModel): string {
  const blocks = [
    ...model.types.map((type) => `  ${renderNativeTsType(type, 'export ')}`),
    ...model.methods.map((method) => {
      const args = method.args
        .map((arg) => `${arg.name}: ${nativeTsType(arg.type, 'argument')}`)
        .join(', ');
      const result = nativeTsType(method.returns, 'result');
      return `  export function ${method.name}(${args}): ${method.async ? `Promise<${result}>` : result};`;
    }),
  ];
  const body = blocks.length > 0 ? `\n${blocks.join('\n\n')}\n` : '\n';
  return `${HEADER}declare module 'soundor:native' {${body}}\n`;
}

/** A declared type as an exported member of the module declaration. */
export function renderNativeTsType(
  type: NativeTypeModel,
  prefix: string,
  indent = '  ',
): string {
  switch (type.kind) {
    case 'enum':
      return `${prefix}type ${type.name} = ${type.values.map((value) => JSON.stringify(value)).join(' | ')};`;
    case 'struct': {
      const fields = type.fields.map(
        (field) =>
          `${indent}  ${field.name}: ${nativeTsType(field.type, 'result')};`,
      );
      return [
        `${prefix}interface ${type.name} {`,
        ...fields,
        `${indent}}`,
      ].join('\n');
    }
  }
}

/**
 * A native type as TypeScript. Arguments accept readonly arrays; results hand
 * out mutable copies. Integers of up to 32 bits and floats are numbers, 64-bit
 * integers bigints, buffers the typed array of their element type.
 */
export function nativeTsType(
  type: NativeType,
  position: 'argument' | 'result',
): string {
  switch (type.kind) {
    case 'void':
      return 'void';
    case 'primitive':
      if (type.name === 'boolean' || type.name === 'string') return type.name;
      return type.name === 'int64' || type.name === 'uint64'
        ? 'bigint'
        : 'number';
    case 'declared':
      return type.name;
    case 'buffer':
      return BUFFER_ARRAY_TYPES[type.element];
    case 'array': {
      const element = nativeTsType(type.element, position);
      return position === 'argument' ? `readonly ${element}[]` : `${element}[]`;
    }
    case 'nullable':
      return `${nativeTsType(type.inner, position)} | null`;
  }
}
