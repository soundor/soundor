/**
 * Renders the TypeScript declaration of the runtime-provided
 * `soundor:parameters` module from the config's parameters. Every parameter is
 * a typed {@link Parameter} whose `info` keeps the exact literal metadata
 * (ids, ranges, options) so UI code can rely on it.
 */

import type { CoreParameter } from './generate';

const HEADER = '// This file was generated by Soundor. Do not edit.\n\n';

const PRELUDE = `  /** Who may change a parameter: the UI and automation, the UI only, or the plugin's processing only. */
  export type ParameterAccess = 'automatable' | 'manual' | 'readOnly';

  /** Metadata of a parameter, as declared in soundor.config. */
  export type ParameterInfo = {
    readonly group?: string;
    readonly role?: 'bypass';
  } & (
    | {
        readonly id: string;
        readonly label: string;
        readonly access: ParameterAccess;
        readonly type: 'int8' | 'uint8' | 'int16' | 'uint16' | 'int32' | 'uint32' | 'float32';
        readonly min: number;
        readonly max: number;
        readonly default: number;
        readonly step?: number;
        readonly unit?: string;
      }
    | {
        readonly id: string;
        readonly label: string;
        readonly access: ParameterAccess;
        readonly type: 'boolean';
        readonly default: boolean;
      }
    | {
        readonly id: string;
        readonly label: string;
        readonly access: ParameterAccess;
        readonly type: 'choice';
        readonly options: readonly { readonly value: string; readonly label: string }[];
        readonly default: string;
      });

  /**
   * A plugin parameter, shared with the DSP and the host. Values are in plain
   * units: numbers within [min, max] on the step's grid (float32 values are
   * 32-bit floats), booleans, or one of a choice's option values.
   */
  export interface Parameter<Value, Info extends ParameterInfo = ParameterInfo> {
    readonly id: Info['id'];
    readonly info: Info;
    /** The current value. */
    get(): Value;
    /**
     * Sets a value or runs an updater synchronously against the latest value, then snaps to the range and step.
     * Changed automatable values notify the host within a gesture; an explicit gesture is reused.
     * Throws a TypeError for a read-only parameter, or a value of the wrong type.
     */
    set(value: Value | ((current: Value) => Value), options?: import('soundor:state-history').HistoryOptions): void;
    /**
     * Calls \`listener\` with the new value after every change, from any source:
     * the UI, host automation, or a preset. Returns a function that unsubscribes.
     */
    subscribe(listener: (value: Value) => void): () => void;
    /** Starts a user interaction (e.g. a drag); the host records the changes until endGesture() as one gesture. */
    beginGesture(options?: import('soundor:state-history').HistoryOptions): void;
    /** Ends the interaction started with beginGesture(). */
    endGesture(): void;
    /** The value (the current one by default) as hosts show it: \`'1.25 kHz'\`. */
    format(value?: Value): string;
    /** Text read as a value, as hosts read typed text; null when it is not one. */
    parse(text: string): Value | null;
    /** The value's (the current one's by default) position in [0, 1], through the parameter's mapping. */
    toNormalized(value?: Value): number;
    /** The value at a position in [0, 1] (clamped), mapped and snapped: what a knob at that position sets. */
    fromNormalized(normalized: number): Value;
  }`;

export function renderParametersDts(
  parameters: readonly CoreParameter[],
): string {
  const entries = [...parameters]
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map(
      (parameter) =>
        `    readonly ${propertyKey(parameter.id)}: Parameter<${valueType(parameter)}, ${infoType(parameter)}>;`,
    );
  const map =
    entries.length > 0
      ? `{\n${entries.join('\n')}\n  }`
      : 'Record<never, never>';
  return `${HEADER}declare module 'soundor:parameters' {
${PRELUDE}

  /** Every parameter declared in soundor.config, by id. */
  export const parameters: ${map};
}
`;
}

function valueType(parameter: CoreParameter): string {
  switch (parameter.type) {
    case 'boolean':
      return 'boolean';
    case 'choice':
      return parameter.options
        .map((option) => JSON.stringify(option.value))
        .join(' | ');
    default:
      return 'number';
  }
}

function infoType(parameter: CoreParameter): string {
  const fields: [string, string][] = [
    ['id', JSON.stringify(parameter.id)],
    ['label', JSON.stringify(parameter.label)],
    ['access', JSON.stringify(parameter.access)],
    ['type', JSON.stringify(parameter.type)],
  ];
  if (parameter.group !== undefined)
    fields.push(['group', JSON.stringify(parameter.group)]);
  if (parameter.role !== undefined)
    fields.push(['role', JSON.stringify(parameter.role)]);
  switch (parameter.type) {
    case 'boolean':
      fields.push(['default', String(parameter.default)]);
      break;
    case 'choice':
      fields.push(
        [
          'options',
          `readonly [${parameter.options.map((option) => `{ readonly value: ${JSON.stringify(option.value)}; readonly label: ${JSON.stringify(option.label)} }`).join(', ')}]`,
        ],
        ['default', JSON.stringify(parameter.default)],
      );
      break;
    default:
      fields.push(
        ['min', String(parameter.min)],
        ['max', String(parameter.max)],
        ['default', String(parameter.default)],
      );
      if (parameter.step !== undefined)
        fields.push(['step', String(parameter.step)]);
      if (parameter.unit !== undefined)
        fields.push(['unit', JSON.stringify(parameter.unit)]);
      break;
  }
  return `{ ${fields.map(([key, type]) => `readonly ${key}: ${type}`).join('; ')} }`;
}

function propertyKey(id: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id);
}
