/**
 * The project-independent declarations of Soundor's runtime, committed as the
 * @soundor/environment package (see scripts/runtime-types.mjs) for libraries
 * that build against it: index.d.ts, all of it in one
 * (`"types": ["@soundor/environment"]`), and its parts, for a library whose
 * toolchain declares image imports itself.
 */

import { renderAssetsDts } from './assets-dts';
import { renderGlobalsDts } from './globals-dts';
import { renderUiDts } from './ui-dts';

const HEADER = '// This file was generated by Soundor. Do not edit.\n\n';

export function runtimeTypeFiles(): { path: string; contents: string }[] {
  return [
    { path: 'assets.d.ts', contents: renderAssetsDts() },
    { path: 'globals.d.ts', contents: renderGlobalsDts() },
    {
      path: 'index.d.ts',
      contents: `${HEADER}/// <reference path="./assets.d.ts" />\n/// <reference path="./globals.d.ts" />\n/// <reference path="./ui.d.ts" />\n`,
    },
    { path: 'ui.d.ts', contents: renderUiDts() },
  ];
}
