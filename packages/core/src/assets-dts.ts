/**
 * Renders the declarations of image and font imports: what Soundor's bundler
 * turns `import logo from './logo.png'` into, the asset's id (`soundor:ui`'s
 * `Asset`, a string). Separate from the globals, so that a library whose own
 * bundler declares these (as plain strings too) needs neither.
 */

const HEADER = '// This file was generated by Soundor. Do not edit.\n\n';

/** The extensions the bundler takes as assets (packages/cli's ASSET_TYPES). */
const EXTENSIONS = ['png', 'jpg', 'jpeg', 'webp', 'ttf', 'otf'];

export function renderAssetsDts(): string {
  return `${HEADER}// A bundled image or font: its id, which soundor:ui resolves (its Asset).
${EXTENSIONS.map(
  (extension) => `declare module '*.${extension}' {
  const asset: string;
  export default asset;
}
`,
).join('')}`;
}
