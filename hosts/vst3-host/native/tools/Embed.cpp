// Writes files into a C++ source as byte arrays:
//
//   soundor_vst3_host_embed <output.cpp> <namespace> (<name> <file>)...
//
// Each <name> becomes `extern const unsigned char name[]` and
// `extern const std::size_t nameSize` in <namespace>.
#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv)
{
    if (argc < 3 || (argc - 3) % 2 != 0)
    {
        std::fputs("usage: soundor_vst3_host_embed <output.cpp> <namespace> (<name> <file>)...\n", stderr);
        return 2;
    }
    std::string code = "// Generated by soundor_vst3_host_embed.\n#include <cstddef>\n\nnamespace ";
    code += argv[2];
    code += "\n{\n";
    for (int index = 3; index < argc; index += 2)
    {
        std::ifstream input(argv[index + 1], std::ios::binary);
        if (! input)
        {
            std::fprintf(stderr, "cannot read %s\n", argv[index + 1]);
            return 1;
        }
        const std::vector<unsigned char> bytes { std::istreambuf_iterator<char>(input),
                                                 std::istreambuf_iterator<char>() };
        const std::string name = argv[index];
        code += "    extern const unsigned char " + name + "[];\n";
        code += "    extern const std::size_t " + name + "Size;\n";
        code += "    alignas(16) const unsigned char " + name + "[] = {";
        for (size_t at = 0; at < bytes.size(); ++at)
        {
            if (at % 24 == 0)
                code += "\n        ";
            code += std::to_string(bytes[at]) + ",";
        }
        code += "\n    };\n    const std::size_t " + name + "Size = " + std::to_string(bytes.size()) + ";\n";
    }
    code += "} // namespace " + std::string(argv[2]) + "\n";
    std::ofstream output(argv[1], std::ios::binary);
    output << code;
    return output ? 0 : 1;
}
